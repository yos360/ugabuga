// Real captures of ugabuga.co.il/learn/gifted-test/bar-ilan
// (src/learn/gifted/BarIlanPage.jsx + barIlan.js). The test seed is Date.now() % 2147483647, so Date.now is
// pinned for the click that starts the test -> seed 1700000001, and the answers come from makeTest itself.
const { chromium } = require('C:/Users/pc/Documents/ugabuga/node_modules/playwright');
const fs = require('fs');
fs.rmSync('shots', { recursive: true, force: true }); fs.mkdirSync('shots', { recursive: true });
const VW = 1280, VH = 1100, SEED = 1700000001;
const WRONG = { 1: null, 8: null, 16: null }; // question index -> wrong pick (first wrong option)
(async () => {
  const { makeTest } = await import('file:///C:/Users/pc/Documents/ugabuga/src/learn/gifted/barIlan.js');
  const qs = makeTest(SEED, 24);
  const pickOf = (i) => (i in WRONG ? (i === 1 ? qs[i].options.indexOf(13) : (qs[i].answer + 1) % 4) : qs[i].answer);
  const b = await chromium.launch({ executablePath: process.env.CHROME_PATH });
  const c = await b.newContext({ viewport: { width: VW, height: VH }, deviceScaleFactor: 2, locale: 'he-IL' });
  await c.addInitScript(() => { const real = Date.now; Date.now = () => (window.__pin ? window.__pin : real()); });
  const p = await c.newPage();
  const hide = () => p.evaluate(() => { for (const e of document.querySelectorAll('body *')) { const s = getComputedStyle(e); if ((s.position === 'fixed' || s.position === 'sticky') && !/ענית על|ציון:/.test(e.textContent) && !e.closest('dialog')) e.style.visibility = 'hidden'; } });
  const vbox = (loc) => loc.evaluate((e) => { const r = e.getBoundingClientRect(); return [r.x, r.y, r.width, r.height].map(Math.round); });
  const boxes = {};
  const scrollTo = async (loc, off) => { await loc.evaluate((e, o) => window.scrollTo(0, e.getBoundingClientRect().top + scrollY - o), off); await p.waitForTimeout(500); };
  const shot = (k) => p.screenshot({ path: `shots/${k}.png` });
  await p.goto('https://ugabuga.co.il/learn/gifted-test/bar-ilan', { waitUntil: 'networkidle' });
  await p.waitForTimeout(2500); await hide();
  const h1 = p.locator('h1');
  await scrollTo(h1, 30);
  boxes.start = { h1: await vbox(h1), full: await vbox(p.getByRole('button', { name: /מבחן מלא/ })), short: await vbox(p.getByRole('button', { name: /תרגול קצר/ })), print: await vbox(p.getByRole('button', { name: /מבחן להדפסה/ })), topics: await vbox(p.locator('p', { hasText: 'הנושאים:' })) };
  console.log('topics:', await p.locator('p', { hasText: 'הנושאים:' }).innerText());
  await shot('start');
  await p.evaluate((s) => { window.__pin = s; }, SEED);
  await p.getByRole('button', { name: /מבחן מלא/ }).click(); await p.waitForTimeout(300);
  await p.evaluate(() => { window.__pin = 0; });
  await p.waitForTimeout(1500); await hide();
  const items = p.locator('ol.space-y-4 > li');
  console.log('count', await items.count(), 'q1:', (await items.nth(0).innerText()).replace(/\n/g, ' | '));
  console.log('q2:', (await items.nth(1).innerText()).replace(/\n/g, ' | '));
  const ol = p.locator('ol.space-y-4');
  await scrollTo(ol, 90);
  const bar = p.locator('div.sticky').first();
  const qb = async () => ({ bar: await vbox(bar), q1: await vbox(items.nth(0)), q2: await vbox(items.nth(1)), o1: await vbox(items.nth(0).getByRole('radio').nth(pickOf(0))), o2: await vbox(items.nth(1).getByRole('radio').nth(pickOf(1))), o2right: await vbox(items.nth(1).getByRole('radio').nth(qs[1].answer)) });
  boxes.q0 = await qb(); await shot('q0');
  await items.nth(0).getByRole('radio').nth(pickOf(0)).click(); await p.waitForTimeout(300);
  boxes.q1 = await qb(); await shot('q1');
  await items.nth(1).getByRole('radio').nth(pickOf(1)).click(); await p.waitForTimeout(300);
  boxes.q2 = await qb(); await shot('q2');
  for (let i = 2; i < 24; i++) await items.nth(i).getByRole('radio').nth(pickOf(i)).click();
  await p.waitForTimeout(400);
  const check = p.getByRole('button', { name: /בדיקה/ });
  await scrollTo(check, VH - 220);
  boxes.done = { bar: await vbox(bar), check: await vbox(check), last: await vbox(items.nth(23)) };
  console.log('bar before check:', await bar.innerText());
  await shot('done');
  await check.click(); await p.waitForTimeout(1500); await hide();
  await scrollTo(ol, 90);
  boxes.c1 = { bar: await vbox(bar), q1: await vbox(items.nth(0)), q2: await vbox(items.nth(1)), ex1: await vbox(items.nth(0).locator('p').last()), ex2: await vbox(items.nth(1).locator('p').last()), o2right: await vbox(items.nth(1).getByRole('radio').nth(qs[1].answer)), o2wrong: await vbox(items.nth(1).getByRole('radio').nth(pickOf(1))) };
  console.log('bar after check:', await bar.innerText());
  console.log('ex2:', await items.nth(1).locator('p').last().innerText());
  await shot('c1');
  const again = p.getByRole('button', { name: /מבחן חדש/ });
  await scrollTo(again, VH - 260);
  boxes.end = { score: await vbox(p.locator('p', { hasText: /^\d+ מתוך 24/ })), again: await vbox(again), printThis: await vbox(p.getByRole('button', { name: /להדפיס את המבחן הזה/ })) };
  console.log('score line:', await p.locator('p', { hasText: /^\d+ מתוך 24/ }).innerText());
  await shot('end');
  await p.getByRole('button', { name: /להדפיס את המבחן הזה/ }).click(); await p.waitForTimeout(3000);
  const dlg = p.locator('dialog.buga-print-dialog');
  boxes.print = { pdf: await vbox(dlg.locator('[data-save-pdf]')), prn: await vbox(dlg.getByRole('button', { name: /הדפסה/ }).last()), page: await vbox(dlg.locator('.buga-preview-pages article').first()) };
  await shot('print');
  const pages = dlg.locator('.buga-preview-pages article');
  console.log('pages', await pages.count());
  await pages.last().evaluate((e) => e.scrollIntoView({ block: 'start' })); await p.waitForTimeout(800);
  boxes.answers = { page: await vbox(pages.last()) };
  await shot('answers');
  fs.writeFileSync('shots/boxes.json', JSON.stringify(boxes, null, 1));
  console.log(JSON.stringify(boxes));
  await b.close();
})().catch((e) => { console.error(e); process.exit(1); });
