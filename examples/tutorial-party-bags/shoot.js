const { chromium } = require('playwright');
const fs = require('fs');
(async () => {
  const b = await chromium.launch();
  const p = await b.newPage({ viewport: { width: 820, height: 1400 }, deviceScaleFactor: 1.5, locale: 'he-IL' });
  await p.goto('http://127.0.0.1:4173/birthday/party-bags', { waitUntil: 'networkidle' });
  await p.waitForTimeout(1500);
  await p.evaluate(() => { for (const e of document.querySelectorAll('body *')) { const c = getComputedStyle(e); if (c.position === 'fixed') e.style.display = 'none'; } });
  const sec = p.locator('#pick-h').locator('xpath=..');
  const pr = p.locator('#print-h').locator('xpath=..');
  const boxes = {};
  const rel = async (loc, base) => { const a = await loc.boundingBox(), c = await base.boundingBox(); return { x: (a.x - c.x) * 1.5, y: (a.y - c.y) * 1.5, w: a.width * 1.5, h: a.height * 1.5 }; };
  const shot = async (name, loc) => { await loc.scrollIntoViewIfNeeded(); await p.waitForTimeout(300); await loc.screenshot({ path: `shots/${name}.png` }); console.log(name, (await p.locator('h3', { hasText: 'כל הרעיונות' }).innerText())); };
  await sec.scrollIntoViewIfNeeded();
  boxes.age = {}; for (const [k, re] of [['toddler', /גיל 2–3/], ['gan', /גן \(4–6\)/], ['young', /כיתות א–ג/], ['older', /כיתות ד–ו/]]) boxes.age[k] = await rel(p.getByRole('button', { name: re }), sec);
  boxes.budget = {}; for (const [k, re] of [['low', /עד 10/], ['mid', /עד 20/], ['high', /עד 35/]]) boxes.budget[k] = await rel(p.getByRole('button', { name: re }), sec);
  boxes.clean = await rel(p.locator('label', { hasText: 'בלי פלסטיק' }), sec);
  boxes.bag = await rel(p.locator('[aria-live=polite]').first(), sec);
  boxes.ideasH = await rel(p.locator('h3', { hasText: 'כל הרעיונות' }), sec);
  await shot('s0-default', sec);
  await p.getByRole('button', { name: /כיתות א–ג/ }).click(); await shot('s1-young', sec);
  await p.getByRole('button', { name: /עד 35/ }).click(); await shot('s2-high', sec);
  await p.getByRole('checkbox').check(); await shot('s3-clean', sec);
  await pr.scrollIntoViewIfNeeded();
  boxes.coloringBtn = await rel(p.getByRole('button', { name: /לצביעה/ }), pr);
  boxes.printBtn = await rel(p.locator('[data-print-main]'), pr);
  await shot('s4-print-color', pr);
  await p.getByRole('button', { name: /לצביעה/ }).click(); await shot('s4-print-coloring', pr);
  await p.locator('[data-print-main]').click(); await p.waitForTimeout(1500);
  await p.screenshot({ path: 'shots/s5-preview.png' });
  fs.writeFileSync('shots/boxes.json', JSON.stringify(boxes, null, 1));
  await b.close();
})();
