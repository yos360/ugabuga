// Prepares today's "החידה היומית" reel: picks the next unused riddle from riddles.json, records it in
// log.json (re-running on the same date reuses the same riddle), and builds a render folder
// work/daily-riddle-<date>/ from template/ (engine, fonts, img) + this folder's score/film/song.
// Usage: node daily-riddle/make.js [YYYY-MM-DD]
const fs = require('fs');
const path = require('path');

const HERE = __dirname, ROOT = path.join(HERE, '..');
const date = process.argv[2] || new Date().toLocaleDateString('en-CA', { timeZone: 'Asia/Jerusalem' });
const riddles = JSON.parse(fs.readFileSync(path.join(HERE, 'riddles.json'), 'utf8'));
const logFile = path.join(HERE, 'log.json');
const log = fs.existsSync(logFile) ? JSON.parse(fs.readFileSync(logFile, 'utf8')) : [];

let entry = log.find((e) => e.date === date);
if (!entry) {
  const used = new Set(log.map((e) => e.id));
  const next = riddles.find((r) => (process.env.RIDDLE_ID ? r.id === process.env.RIDDLE_ID : !used.has(r.id)));
  if (!next) { console.error('NO_RIDDLES_LEFT: add new riddles to daily-riddle/riddles.json'); process.exit(2); }
  entry = { date, n: log.length + 1, id: next.id, answer: next.answer, posted: false };
  log.push(entry);
  fs.writeFileSync(logFile, JSON.stringify(log, null, 2) + '\n');
}
const riddle = riddles.find((r) => r.id === entry.id);
const prevEntry = log.filter((e) => e.n < entry.n).pop();
const prev = prevEntry ? { n: prevEntry.n, answer: prevEntry.answer, why: riddles.find((r) => r.id === prevEntry.id)?.why || '' } : null;
const left = riddles.length - new Set(log.map((e) => e.id)).size;

// ---------- the render folder ----------
const out = path.join(ROOT, 'work', `daily-riddle-${date}`);
fs.mkdirSync(out, { recursive: true });
for (const d of ['engine', 'fonts', 'img']) fs.cpSync(path.join(ROOT, 'template', d), path.join(out, d), { recursive: true });
for (const f of ['score.js', 'film.js', 'song.js']) fs.copyFileSync(path.join(HERE, f), path.join(out, f));
fs.copyFileSync(path.join(ROOT, 'template', 'package.json'), path.join(out, 'package.json'));
const data = { ...riddle, n: entry.n, date, prev };
fs.writeFileSync(path.join(out, 'riddle.js'),
  `// generated by daily-riddle/make.js\n(function () { const R = ${JSON.stringify(data, null, 2)};\n` +
  `if (typeof module !== 'undefined' && module.exports) module.exports = R; else globalThis.RIDDLE = R; })();\n`);
const html = fs.readFileSync(path.join(ROOT, 'template', 'index.html'), 'utf8')
  .replace('<script src="score.js"></script>', '<script src="riddle.js"></script>\n<script src="score.js"></script>');
if (!html.includes('riddle.js')) throw new Error('template/index.html: score.js script tag not found');
fs.writeFileSync(path.join(out, 'index.html'), html);

// ---------- captions ----------
const up = path.join(ROOT, 'uploads', 'daily-riddle', date);
fs.mkdirSync(up, { recursive: true });
const question = riddle.kind === 'text' ? riddle.lines.join(' ').replace(/\s+/g, ' ') : `${riddle.title}\n${(riddle.items || riddle.lines).join(riddle.kind === 'seq' ? ' · ' : '\n')}`;
const prevLine = prev ? `\n\n✅ התשובה לחידה היומית #${prev.n}: ${prev.answer}\n(${prev.why})` : '';
const main = `🧠 החידה היומית #${entry.n} — יש לכם 10 שניות!\n${question}${prevLine}\n\n✍️ כתבו את התשובה בתגובות — ואל תגלו למי שעוד חושב 🤫\nהתשובה — מחר ב־18:00, עם החידה הבאה ⏰\n\nעוד חידות, משחקים ודפים להדפסה — בחינם: https://ugabuga.co.il\n\n#עוגה_בוגה #החידה_היומית #חידות #חידה_קשה #חידות_היגיון`;
const yt = `החידה היומית #${entry.n} 🧠 ${riddle.title} — 10 שניות #shorts`;
const ytDesc = main.replace('✍️ כתבו את התשובה בתגובות — ואל תגלו למי שעוד חושב 🤫\n', 'נסו לפתור לפני שנגמר הזמן 👀\n');
fs.writeFileSync(path.join(up, 'captions.md'),
  `=== כיתוב ראשי (פייסבוק / טיקטוק / ערוץ הוואטסאפ) ===\n${main}\n\n=== אינסטגרם ===\n${main.replace('https://ugabuga.co.il', 'בקישור שבביו 🔗')}\n\n=== יוטיוב — כותרת ===\n${yt}\n\n=== יוטיוב — תיאור (סרטון לילדים: התגובות כבויות) ===\n${ytDesc}\n`);

console.log(JSON.stringify({ date, n: entry.n, id: entry.id, answer: entry.answer, dir: out, captions: path.join(up, 'captions.md'), riddlesLeft: left }));
