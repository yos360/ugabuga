test('equation solver', () => {
  const l = T.solveLinear(2, 3, 11)
  assert.equal(l.roots[0], 4)
  assert.equal(T.solveLinear(0, 2, 2).kind, 'all')
  assert.equal(T.solveLinear(0, 2, 3).kind, 'none')
  const q = T.solveQuadratic(1, -5, 6)
  assert.deepEqual(q.roots, [2, 3])
  assert.deepEqual(q.exact, ['2', '3'])
  assert.equal(q.D, 1)
  const s = T.solveQuadratic(1, -2, -1)
  assert.deepEqual(s.exact, ['1 − √2', '1 + √2'])
  const g = T.solveQuadratic(1, -1, -1)
  assert.deepEqual(g.exact, ['(1 − √5)/2', '(1 + √5)/2'])
  assert.deepEqual(T.solveQuadratic(2, 0, -1).exact, ['−√2/2', '√2/2'])
  assert.deepEqual(T.solveQuadratic(1, 2, 1).exact, ['−1'])
  assert.equal(T.solveQuadratic(1, 0, 1).kind, 'none')
  assert.deepEqual(T.solveQuadratic(2, -3, 1).exact, ['1/2', '1'])
  assert.deepEqual(T.solveQuadratic(1, -2, 0).vertex, [1, -1])
  const sys = T.solve2x2(1, 1, 10, 1, -1, 2)
  assert.deepEqual([sys.x, sys.y], [6, 4])
  assert.deepEqual(T.solve2x2(1, 2, 1, 3, 4, 2).exact, ['0', '1/2'])
  assert.equal(T.solve2x2(1, 1, 2, 2, 2, 4).kind, 'all')
  assert.equal(T.solve2x2(1, 1, 2, 2, 2, 5).kind, 'none')
  assert.equal(T.readNum('1/2'), 0.5)
  assert.equal(T.readNum('√4'), 2)
  assert.equal(T.readNum('2,5'), 2.5)
  assert.equal(T.readNum('abc'), null)
})

test('statistics', () => {
  const { nums, bad } = T.parseList('4, 8; 15\n16 23 42 x')
  assert.deepEqual(nums, [4, 8, 15, 16, 23, 42])
  assert.deepEqual(bad, ['x'])
  const s = T.stats(nums)
  assert.equal(s.mean, 18)
  assert.equal(s.median, 15.5)
  assert.equal(s.range, 38)
  assert.deepEqual(s.modes, [])
  assert.equal(s.q1, 8)
  assert.equal(s.q3, 23)
  const t = T.stats([2, 4, 4, 4, 5, 5, 7, 9])
  assert.equal(t.mean, 5)
  assert.equal(t.sdP, 2)
  assert.equal(t.varP, 4)
  assert.deepEqual(t.modes, [4])
  assert.equal(Number(t.sdS.toFixed(4)), 2.1381)
  const odd = T.stats([1, 2, 3, 4, 5, 6, 7])
  assert.equal(odd.median, 4)
  assert.equal(odd.q1, 2)
  assert.equal(odd.q3, 6)
  assert.equal(T.stats([5]).sdS, null)
  assert.equal(T.stats([]), null)
  assert.equal(T.stats([0.1, 0.2]).sum, 0.3)
})

test('graph zeros and intersections', () => {
  assert.deepEqual(T.findZeros(C.compile('x²−4'), -10, 10), [-2, 2])
  assert.deepEqual(T.findZeros(C.compile('x²'), -5, 5.3), [0])
  assert.deepEqual(T.findZeros(C.compile('(x−1)²'), -5, 5.3), [1])
  assert.deepEqual(T.findZeros(C.compile('x²+1'), -5, 5), [])
  const f = C.compile('x²−4'); const g = C.compile('2x+1')
  const xs = T.findZeros(x => f(x) - g(x), -10, 10)
  assert.equal(xs.length, 2)
  assert.ok(Math.abs(xs[0] - (1 - Math.sqrt(6))) < 1e-8)
  // tan's poles are not zeros
  const z = T.findZeros(C.compile('tan(x)', { angle: 'rad' }), -2, 2)
  assert.deepEqual(z, [0])
})

