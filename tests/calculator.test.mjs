// /tools/calculator: parser, precedence, trig, formatting, exact forms, explanation, editing, school tabs
import { test } from 'node:test'
import assert from 'node:assert/strict'
const C = await import('../src/office/calc/calcEngine.js')
const T = await import('../src/office/calc/mathTools.js')

const val = (src, ctx = {}) => {
  const r = C.evaluate(src, ctx)
  assert.ok(r.ok, `${src}: ${r.error}`)
  return Number(r.value.toPrecision(12))
}
const err = (src, ctx = {}) => { const r = C.evaluate(src, ctx); assert.equal(r.ok, false, src); return r }
const show = (src, ctx) => C.formatDecimal(C.evaluate(src, ctx).value).text
const exact = (src, ctx) => C.exactText(C.exactForm(C.evaluate(src, ctx).value))

test('precedence and associativity', () => {
  assert.equal(val('2+3×4'), 14)
  assert.equal(val('(2+3)×4'), 20)
  assert.equal(val('10−4−3'), 3)
  assert.equal(val('100÷10÷5'), 2)
  assert.equal(val('2^3^2'), 512)
  assert.equal(val('−2^2'), -4)
  assert.equal(val('(−2)^2'), 4)
  assert.equal(val('2^−1'), 0.5)
  assert.equal(val('2*3-4/2'), 4)
  assert.equal(val('3²+4²'), 25)
  assert.equal(val('5×−3'), -15)
  assert.equal(val('−−4'), 4)
})

test('implicit multiplication and auto-closed parentheses', () => {
  assert.equal(val('2π'), Number((2 * Math.PI).toPrecision(12)))
  assert.equal(val('3(4+1)'), 15)
  assert.equal(val('(1+2)(3+4)'), 21)
  assert.equal(val('2√(9)'), 6)
  assert.equal(val('1÷2π'), Number((1 / (2 * Math.PI)).toPrecision(12)))
  assert.equal(val('2(3'), 6)
  assert.equal(val('√(16'), 4)
  assert.equal(val('sin(30'), 0.5)
  assert.equal(val('√9+1'), 4)
})

test('functions, constants, postfix', () => {
  assert.equal(val('5!'), 120)
  assert.equal(val('0!'), 1)
  assert.equal(val('5P2'), 20)
  assert.equal(val('5C2'), 10)
  assert.equal(val('52C5'), 2598960)
  assert.equal(val('∛(−8)'), -2)
  assert.equal(val('abs(−7)'), 7)
  assert.equal(val('log(1000)'), 3)
  assert.equal(val('ln(e)'), 1)
  assert.equal(val('e^(2)'), Number(Math.exp(2).toPrecision(12)))
  assert.equal(val('10^(3)'), 1000)
  assert.equal(val('4⁻¹'), 0.25)
  assert.equal(val('frac(3;4)'), 0.75)
  assert.equal(val('root(3;27)'), 3)
  assert.equal(val('root(3;−27)'), -3)
  assert.equal(val('(−8)^(1÷3)'), -2)
  assert.equal(val('Ans+1', { ans: 41 }), 42)
  assert.equal(val('2M', { mem: 5 }), 10)
  assert.equal(val('sqrt(2)^2'), 2)
})

test('percent', () => {
  assert.equal(val('50%'), 0.5)
  assert.equal(val('200+10%'), 220)
  assert.equal(val('200−10%'), 180)
  assert.equal(val('200×10%'), 20)
})

test('trigonometry in degrees (default) and radians', () => {
  assert.equal(val('sin(30)'), 0.5)
  assert.equal(val('sin(180)'), 0)
  assert.equal(val('cos(90)'), 0)
  assert.equal(val('cos(60)'), 0.5)
  assert.equal(val('tan(45)'), 1)
  assert.equal(val('sin(−90)'), -1)
  assert.equal(val('sin⁻¹(0.5)'), 30)
  assert.equal(val('cos⁻¹(0)'), 90)
  assert.equal(val('tan⁻¹(1)'), 45)
  assert.equal(val('sin(π)', { angle: 'rad' }), 0)
  assert.equal(val('cos(π)', { angle: 'rad' }), -1)
  assert.equal(val('sin⁻¹(1)', { angle: 'rad' }), Number((Math.PI / 2).toPrecision(12)))
  assert.equal(err('tan(90)').error, 'tan לא מוגדר בזווית הזו (90°, 270°…)')
  assert.ok(err('tan(π÷2)', { angle: 'rad' }).error.startsWith('tan'))
})

test('Hebrew errors point at the problem', () => {
  const d = err('5÷0')
  assert.equal(d.error, 'חלוקה באפס')
  assert.deepEqual([d.s, d.e], [1, 3])
  assert.equal(err('√(−4)').error, 'שורש של מספר שלילי')
  assert.equal(err('log(0)').error, 'log של אפס או של מספר שלילי אינו מוגדר')
  assert.equal(err('sin⁻¹(2)').error, 'sin⁻¹ מקבל רק מספרים בין 1− ל־1')
  assert.equal(err('2+').error, 'חסר מספר אחרי +')
  assert.equal(err('×3').error, 'חסר מספר לפני ×')
  assert.equal(err('()').error, 'הסוגריים ריקים — חסר מספר בתוכם')
  const extra = err('2+3)')
  assert.equal(extra.error, 'יש סוגר „)” מיותר')
  assert.equal(extra.s, 3)
  assert.equal(err('2#3').error, 'תו לא מוכר: „#”')
  assert.equal(err('(−3)!').error, 'עצרת (!) רק למספר שלם בין 0 ל־170')
  assert.equal(err('0^0').error, '0 בחזקת 0 אינו מוגדר')
  assert.equal(err('frac(1;0)').error, 'חלוקה באפס — המכנה הוא 0')
  assert.equal(err('frac(1').error, 'חסר מכנה לשבר')
  assert.equal(err('10^(400)').error, 'המספר גדול מדי')
  assert.equal(err('2C5').error, 'nCr צריך מספרים שלמים עם n ≥ r ≥ 0')
  assert.equal(C.evaluate('').empty, true)
})

test('decimal formatting has no float noise', () => {
  assert.equal(show('0.1+0.2'), '0.3')
  assert.equal(show('1÷3'), '0.3333333333…')
  assert.equal(show('2÷3'), '0.6666666667…')
  assert.equal(show('√(2)'), '1.414213562…')
  assert.equal(show('1.1×1.1'), '1.21')
  assert.equal(show('2^40'), '1.099511628×10¹²…')
  assert.equal(show('10^(12)'), '1×10¹²')
  assert.equal(show('1÷10^(7)'), '1×10⁻⁷')
  assert.equal(show('3−5'), '−2')
  assert.equal(show('123456789'), '123456789')
  assert.equal(C.formatDecimal(0).text, '0')
  assert.equal(C.formatDecimal(-0).text, '0')
})

test('exact forms: fractions, roots, π', () => {
  assert.equal(exact('0.75'), '3/4')
  assert.equal(exact('0.1+0.2'), '3/10')
  assert.equal(exact('1÷3'), '1/3')
  assert.equal(exact('1÷3+1÷6'), '1/2')
  assert.equal(exact('√(8)'), '2√2')
  assert.equal(exact('√(12)÷4'), '√3/2')
  assert.equal(exact('sin(60)'), '√3/2')
  assert.equal(exact('cos(45)'), '√2/2')
  assert.equal(exact('tan(30)'), '√3/3')
  assert.equal(exact('−√(18)'), '−3√2')
  assert.equal(exact('π÷6'), 'π/6')
  assert.equal(exact('sin⁻¹(0.5)', { angle: 'rad' }), 'π/6')
  assert.equal(exact('2π'), '2π')
  assert.equal(exact('7÷4'), '7/4')
  assert.equal(C.exactText(C.exactForm(7 / 4), { mixed: true }), '1 3/4')
  assert.equal(C.exactForm(Math.E), null)
  assert.equal(C.exactForm(Math.log(2)), null)
  assert.equal(C.isNiceExact(C.exactForm(5)), false)
  assert.equal(C.isNiceExact(C.exactForm(0.5)), true)
  assert.equal(val(C.exactSource(C.exactForm(Math.sqrt(8)))), Number(Math.sqrt(8).toPrecision(12)))
  assert.equal(val(C.exactSource(C.exactForm(-3 / 4))), -0.75)
})

test('step-by-step explanation follows the order of operations', () => {
  const r = C.explain('2+3×4')
  assert.deepEqual(r.steps.map(s => s.expr), ['2 + 12', '14'])
  assert.match(r.steps[0].label, /כפל/)
  const p = C.explain('(1+2)×3')
  assert.deepEqual(p.steps.map(s => s.expr), ['3 × 3', '9'])
  assert.equal(p.steps[0].inParens, true)
  const w = C.explain('2^3×2+1')
  assert.deepEqual(w.steps.map(s => s.expr), ['8 × 2 + 1', '16 + 1', '17'])
  assert.match(w.steps[0].label, /חזקה/)
  const pct = C.explain('200+10%')
  assert.deepEqual(pct.steps.map(s => s.expr), ['220'])
  assert.equal(C.explain('5÷0').error, 'חלוקה באפס')
  assert.equal(C.explain('sin(30)+1').steps[0].expr, '1/2 + 1')
  assert.deepEqual(C.explain('frac(1;3)+2^(2)').steps.map(s => s.expr), ['1/3 + 4', '13/3'])
  assert.deepEqual(C.explain('2×(3+4)²−5').steps.map(s => s.expr), ['2 × 7² − 5', '2 × 49 − 5', '98 − 5', '93'])
})

test('editing helpers: cursor, backspace, insert', () => {
  assert.equal(C.moveCursor('sin(30)', 7, -1), 6)
  assert.equal(C.moveCursor('sin(30)', 6, -1), 5)
  assert.equal(C.moveCursor('sin(30)', 4, -1), 0)
  assert.equal(C.moveCursor('sin(30)', 0, 1), 4)
  assert.deepEqual(C.deleteBefore('12+sin(30)', 7), { src: '12+30', cur: 3 })
  assert.deepEqual(C.deleteBefore('123', 3), { src: '12', cur: 2 })
  assert.deepEqual(C.deleteBefore('2+Ans', 5), { src: '2+', cur: 2 })
  assert.deepEqual(C.deleteBefore('(2)', 3), { src: '(2)', cur: 2 })
  assert.deepEqual(C.deleteBefore('frac(3;4)', 5), { src: '3÷4', cur: 0 })
  assert.deepEqual(C.insertAt('2+', 2, 'sin()', 4), { src: '2+sin()', cur: 6 })
})

