// Builds the light story index (titles, ages, themes, summaries — no story text) for /stories, plus
// the site-search entries and sitemap lines for the stories in src/data/stories/batch-*.js.
// The full text of a story is loaded only when its page is opened (src/data/storyLibrary.js).
// Run after adding or editing a batch: node scripts/build-story-index.mjs
import { readdirSync, readFileSync, writeFileSync } from 'node:fs'
import { BEDTIME_STORIES, STORY_AGES, STORY_THEMES, renderStory, storyWords } from '../src/data/bedtimeStories.js'

const dir = new URL('../src/data/stories/', import.meta.url)
const batches = readdirSync(dir).filter(f => /^batch-\d+\.js$/.test(f)).sort()
const all = BEDTIME_STORIES.map(s => ({ s, src: 'core' }))
for (const f of batches) for (const s of (await import(new URL(f, dir).href)).STORIES) all.push({ s, src: f.replace(/\.js$/, '') })

const meta = ({ s, src }) => ({ slug: s.slug, title: s.title, emoji: s.emoji, age: s.age, theme: s.theme, chars: s.chars, summary: s.summary, words: storyWords(s), src })
const index = all.map(meta)
writeFileSync(new URL('../src/data/storyIndex.js', import.meta.url),
  `// Generated by scripts/build-story-index.mjs — do not edit by hand.\n// Every bedtime story without its text: enough for the /stories library, cards and related links.\nexport const STORY_INDEX = ${JSON.stringify(index)}\n`)
writeFileSync(new URL('../src/data/bedtimeStoryCount.js', import.meta.url),
  `// How many stories the /stories library has (generated by scripts/build-story-index.mjs). Pages that only\n// mention the number import this instead of the story index.\nexport const BEDTIME_STORY_COUNT = ${index.length}\n`)

// Site search: the 30 original stories have hand-written entries in searchStatic.js; the rest come from here.
const ageLabel = id => STORY_AGES.find(a => a.id === id).label
const themeLabel = id => STORY_THEMES.find(t => t.id === id).label
const search = all.filter(x => x.src !== 'core').map(({ s }) => {
  const title = renderStory(s).title
  return { to: `/stories/${s.slug}`, title: `${title} — סיפור לפני השינה`, emoji: s.emoji, kind: 'tool', desc: `${ageLabel(s.age)} · ${themeLabel(s.theme)}`, keys: `סיפור לפני השינה סיפור ילדים ${themeLabel(s.theme)} ${title}` }
})
writeFileSync(new URL('../src/data/storySearch.js', import.meta.url),
  `// Generated by scripts/build-story-index.mjs — do not edit by hand. Site-search entries for the added stories.\nexport const STORY_SEARCH = ${JSON.stringify(search)}\n`)

// Sitemap: add any story page that is missing (the hand-kept file is also the prerender list).
const smUrl = new URL('../public/sitemap-static.xml', import.meta.url)
let sm = readFileSync(smUrl, 'utf8')
const missing = all.filter(({ s }) => !sm.includes(`<loc>https://ugabuga.co.il/stories/${s.slug}</loc>`))
if (missing.length) {
  const lines = missing.map(({ s }) => `  <url><loc>https://ugabuga.co.il/stories/${s.slug}</loc><lastmod>${new Date().toISOString().slice(0, 10)}</lastmod><priority>0.6</priority></url>`).join('\n')
  sm = sm.replace('</urlset>', `${lines}\n</urlset>`)
  writeFileSync(smUrl, sm)
}
console.log(`story index: ${index.length} stories (${batches.length} batch files); ${missing.length} added to the sitemap`)
