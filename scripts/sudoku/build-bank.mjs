// Builds src/sudoku/bank.js — graded 9×9 base puzzles for the /sudoku pages.
// Run: node scripts/sudoku/build-bank.mjs   (deterministic: same seeds -> same bank)
// The site never generates 9×9 boards in the browser; it picks a base puzzle from this
// bank and applies a seeded, validity-preserving transformation (see src/sudoku/engine.js).
import { writeFile } from 'node:fs/promises'
import { generate, rng, toString, LEVELS_9 } from '../../src/sudoku/engine.js'

const PER_LEVEL = 80
const bank = {}
for (const [li, level] of LEVELS_9.entries()) {
  const seen = new Set(), out = []
  for (let seed = 1; out.length < PER_LEVEL; seed++) {
    const { puzzle } = generate(level, rng(1000003 * (li + 1) + seed))
    const s = toString(puzzle)
    if (!seen.has(s)) { seen.add(s); out.push(s) }
  }
  bank[level] = out
  console.log(level, out.length)
}
const body = `// GENERATED by scripts/sudoku/build-bank.mjs — do not edit by hand.
// ${PER_LEVEL} graded base puzzles per level, 81 chars each ('.' = empty). Each has exactly one
// solution and its level was assigned by grade() in src/sudoku/engine.js.
export const BANK = ${JSON.stringify(bank, null, 1)}
`
await writeFile(new URL('../../src/sudoku/bank.js', import.meta.url), body)
