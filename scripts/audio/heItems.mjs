const vocal = /[ְ-ׇּׁׂ]/
const tts = w => V[w] || (vocal.test(w) ? w : null)

export function heItems() {
  const items = new Map()
  const add = (key, text) => { if (!text) throw new Error(`no vocalized text for "${key}"`); items.set(key.normalize('NFC'), text) }
  add('איך קוראים לאות הזאת?', 'אֵיךְ קוֹרְאִים לָאוֹת הַזֹּאת?')
  for (const h of HEBREW) {
    add(h.name, h.name)
    add(`לחצו על האות ${h.name}`, `לַחֲצוּ עַל הָאוֹת ${h.name}`)
    for (const w of h.words) add(w[2] || w[0], tts(w[2] || w[0]))
  }
  for (const d of DICTATION) for (const w of d.words) add(w, tts(w))
  for (const w of ['חתול', 'כלב', 'בית', 'שמש', 'ספר', 'פרח']) add(`מצאו את המילה ${w}`, `מִצְאוּ אֶת הַמִּלָּה ${V[w]}`)
  return [...items].map(([key, text]) => ({ key, text }))
}
