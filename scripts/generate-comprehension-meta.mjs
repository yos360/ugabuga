// Builds src/en/comprehension/meta.js: one small English card per English unseen test (title, level,
// genre, summary, size), from the Hebrew site's index and the English overlays in src/en/comprehension/i18n/.
import { writeFile, readdir } from 'node:fs/promises'
import { UNSEEN_INDEX } from '../src/data/unseen/index.js'

const dir = new URL('../src/en/comprehension/i18n/', import.meta.url)
const files = (await readdir(dir)).filter(f => f.endsWith('.js'))
const overlay = {}
for (const f of files) Object.assign(overlay, (await import(new URL(f, dir))).EN)

const cards = UNSEEN_INDEX.filter(t => t.lang === 'en' && overlay[t.slug]).map(t => ({
  slug: t.slug, level: t.level, title: t.title, genre: overlay[t.slug].genre, summary: overlay[t.slug].summary, words: t.words, questions: t.questions, file: t.file,
}))
const missing = UNSEEN_INDEX.filter(t => t.lang === 'en' && !overlay[t.slug]).map(t => t.slug)
await writeFile(new URL('../src/en/comprehension/meta.js', import.meta.url),
  `// Generated by scripts/generate-comprehension-meta.mjs — do not edit by hand.\nexport const RC_META = ${JSON.stringify(cards, null, 1)}\n`)
console.log(`Reading comprehension: ${cards.length} English cards${missing.length ? `, missing overlays: ${missing.join(', ')}` : ''}`)
