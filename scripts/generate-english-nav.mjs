import { writeFile } from 'node:fs/promises'
import { ENGLISH_PAGES, ENGLISH_SECTIONS } from '../src/en/englishRoutes.js'
const pairs = ENGLISH_PAGES.filter(p => p.counterpart)
// englishLinks.js is in the entry bundle (SEO, Navbar), so the pairs are stored compactly:
// - RULES: whole Hebrew families where every page has an English twin (their tests enforce it), stored as
//   one [hebrewPrefix, englishPrefix] rule instead of one pair per page;
// - a bare Hebrew path when the English one is simply "/en" + it;
// - otherwise [hebrew, english]. Explicit pairs win over rules (e.g. holiday drawings with their own pages).
const RULES = [
  ['/printables/coloring/', '/en/coloring-pages/', /^\/printables\/coloring\/[^/]+(\/\d+)?$/],
  ['/how-to-draw/', '/en/how-to-draw/', /^\/how-to-draw\/[^/]+$/],
  ['/printables/color-by-number/', '/en/printables/color-by-number/', /^\/printables\/color-by-number\/[^/]+$/],
  ['/tools/escape-rooms/', '/en/tools/escape-rooms/', /^\/tools\/escape-rooms\/.+$/],
]
const byRule = p => RULES.some(([he, en, re]) => re.test(p.counterpart) && p.path === en + p.counterpart.slice(he.length))
// The rest are grouped by their pair of parent folders: DIRS[i] = [hebrew folder, english folder], and each
// pair is "i|name" (same last segment) or "i|hebrewName|englishName".
const dir = s => s.slice(0, s.lastIndexOf('/') + 1)
const DIRS = [], dirIndex = new Map()
const PAIRS = pairs.filter(p => !byRule(p)).map(({ counterpart: he, path: en }) => {
  const key = dir(he) + ' ' + dir(en)
  if (!dirIndex.has(key)) { dirIndex.set(key, DIRS.length); DIRS.push([dir(he), dir(en)]) }
  const a = he.slice(dir(he).length), b = en.slice(dir(en).length)
  return dirIndex.get(key) + '|' + a + (a === b ? '' : '|' + b)
}).join(' ')
const RULES_OUT = RULES.map(([he, en, re]) => [he, en, re.source])
const content = `// Generated by scripts/generate-english-nav.mjs from the route catalog.
export const ENGLISH_SECTIONS = ${JSON.stringify(ENGLISH_SECTIONS)}
const DIRS = ${JSON.stringify(DIRS)}
const PAIRS = ${JSON.stringify(PAIRS)}
const RULES = ${JSON.stringify(RULES_OUT)}.map(([he, en, re]) => [he, en, new RegExp(re)])
const COUNTERPARTS = {}, HEBREW = {}
for (const p of PAIRS.split(' ')) {
  const [i, a, b = a] = p.split('|'), [hd, ed] = DIRS[i], he = (hd + a).replace(/(.)\\/$/, '$1'), en = (ed + b).replace(/(.)\\/$/, '$1')
  COUNTERPARTS[he] = en; HEBREW[en] = he
}
const clean = path => path?.replace(/\\/+$/, '') || '/'
export const englishCounterpart = path => {
  const p = clean(path)
  if (COUNTERPARTS[p]) return COUNTERPARTS[p]
  for (const [he, en, re] of RULES) if (re.test(p)) return en + p.slice(he.length)
}
export const hebrewCounterpart = path => {
  const p = clean(path)
  if (HEBREW[p]) return HEBREW[p]
  for (const [he, en, re] of RULES) if (p.startsWith(en) && re.test(he + p.slice(en.length)) && !COUNTERPARTS[he + p.slice(en.length)]) return he + p.slice(en.length)
}
`
await writeFile(new URL('../src/en/englishLinks.js', import.meta.url), content)
console.log(`English navigation: ${ENGLISH_SECTIONS.length} sections, ${pairs.length} reciprocal links (${pairs.filter(byRule).length} by rule)`)
