import { writeFile } from 'node:fs/promises'
import { ENGLISH_PAGES, ENGLISH_SECTIONS } from '../src/en/englishRoutes.js'
const pairs = ENGLISH_PAGES.filter(p => p.counterpart)
// englishLinks.js is in the entry bundle (SEO, Navbar), so the pairs are stored once and compactly:
// a bare Hebrew path when the English one is simply "/en" + it, otherwise [hebrew, english].
const PAIRS = pairs.map(p => p.path === '/en' + p.counterpart ? p.counterpart : [p.counterpart, p.path])
const content = `// Generated by scripts/generate-english-nav.mjs from the route catalog.
export const ENGLISH_SECTIONS = ${JSON.stringify(ENGLISH_SECTIONS)}
const PAIRS = ${JSON.stringify(PAIRS)}
const COUNTERPARTS = {}, HEBREW = {}
for (const p of PAIRS) { const [he, en] = typeof p === 'string' ? [p, '/en' + p] : p; COUNTERPARTS[he] = en; HEBREW[en] = he }
export const englishCounterpart = path => COUNTERPARTS[path?.replace(/\\/+$/, '') || '/']
export const hebrewCounterpart = path => HEBREW[path?.replace(/\\/+$/, '') || '/']
`
await writeFile(new URL('../src/en/englishLinks.js', import.meta.url), content)
console.log(`English navigation: ${ENGLISH_SECTIONS.length} sections, ${pairs.length} reciprocal links`)
