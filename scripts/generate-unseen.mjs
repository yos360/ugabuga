// Builds src/data/unseen/index.js (a light list of every unseen test — the pages load a test's text only
// when it opens) and writes the unseen pages into public/sitemap-static.xml and src/data/searchStatic.js.
//   node scripts/generate-unseen.mjs        (tests/unseen.test.mjs fails when the files are out of date)
import { readFile, writeFile, readdir } from 'node:fs/promises'
import { UNSEEN_LEVELS } from '../src/data/unseen/levels.js'

const dir = new URL('../src/data/unseen/', import.meta.url)
const files = (await readdir(dir)).filter(f => /^tests-.*\.js$/.test(f)).sort()
const words = s => String(s).trim().split(/\s+/).filter(w => /[\p{L}\d]/u.test(w)).length
const LANG_PATH = { en: 'english', he: 'hebrew' }
// Writers may name the genre in English; cards and titles show it in Hebrew.
const GENRE_HE = { 'personal story': 'סיפור אישי', story: 'סיפור', 'informative text': 'טקסט מידע', informative: 'טקסט מידע', 'expository text': 'טקסט עיוני',
  'human-interest article': 'כתבה אנושית', 'human interest': 'כתבה אנושית', 'feature article': 'כתבה עיונית', article: 'כתבה', review: 'ביקורת', 'book review': 'ביקורת ספר',
  opinion: 'מאמר דעה', 'opinion piece': 'מאמר דעה', 'opinion article': 'מאמר דעה', essay: 'מסה', 'news report': 'ידיעה חדשותית', report: 'דיווח', interview: 'ראיון',
  letter: 'מכתב', notice: 'מודעה', diary: 'יומן', 'diary entry': 'יומן', advertisement: 'מודעה', tips: 'עצות', 'argumentative essay': 'מאמר טיעון' }
const genreHe = g => GENRE_HE[String(g).toLowerCase().trim()] || g
const index = []
for (const file of files) {
  const { TESTS } = await import(new URL(file, dir))
  for (const t of TESTS) index.push({ slug: t.slug, lang: t.lang, level: t.level, title: t.title, genre: genreHe(t.genre), topic: t.topic, summary: t.summary,
    words: t.texts.reduce((s, x) => s + words((x.paragraphs || []).join(' ')), 0), questions: t.questions.length, file })
}
const order = new Map(UNSEEN_LEVELS.map((l, i) => [l.lang + l.id, i]))
index.sort((a, b) => order.get(a.lang + a.level) - order.get(b.lang + b.level))
await writeFile(new URL('index.js', dir), `// Generated by scripts/generate-unseen.mjs — do not edit by hand.\nexport const UNSEEN_INDEX = ${JSON.stringify(index, null, 1)}\n`)

const today = new Date().toISOString().slice(0, 10)
const q = s => String(s).replace(/\\/g, '\\\\').replace(/'/g, "\\'")
const urls = [], rows = []
const add = (path, prio, row) => { urls.push(`  <url><loc>https://ugabuga.co.il${path}</loc><lastmod>${today}</lastmod><priority>${prio}</priority></url>`); if (row) rows.push(`  { to: '${path}', ${row} },`) }
add('/unseen', '0.9', `title: 'אנסין — תרגול באנגלית ובעברית', emoji: '📝', kind: 'tool', desc: 'אנסינים מקוריים לכיתות ז׳–י״ב ולבגרות, עם שאלות אמריקאיות, הסברים וטיימר.', keys: 'אנסין אנסינים unseen אנסין באנגלית אנסין בגרות תרגול אנסין הבנת הנקרא בגרות'`)
for (const [lang, path] of Object.entries(LANG_PATH)) {
  const he = lang === 'he'
  add(`/unseen/${path}`, '0.8', he
    ? `title: 'אנסין בעברית — הבנת הנקרא לכיתה ט׳ ולבגרות', emoji: '📝', kind: 'tool', desc: 'טקסט עיוני, טיעוני וטבלה, כמו בבגרות בלשון.', keys: 'אנסין בעברית הבנת הנקרא בגרות לשון בגרות בלשון הבנה והבעה מטלת מיזוג'`
    : `title: 'אנסין באנגלית — Unseen לכיתות ז׳–י״ב', emoji: '📝', kind: 'tool', desc: 'Unseen באנגלית לפי רמה: ז׳, ח׳, ט׳, 3, 4 ו־5 יחידות.', keys: 'אנסין באנגלית unseen english אנסין מודול C מודול E מודול G אנסין 5 יחידות אנסין 4 יחידות'`)
  for (const L of UNSEEN_LEVELS.filter(l => l.lang === lang)) {
    const name = he ? `אנסין בעברית — ${L.name}` : `אנסין באנגלית — ${L.name}`
    add(`/unseen/${path}/${L.path}`, '0.8', `title: '${q(name)}', emoji: '📝', kind: 'tool', desc: '${q(L.about)}', keys: '${q(name)} אנסין ${q(L.short)} ${he ? 'הבנת הנקרא' : 'unseen'} ${q(L.name)}'`)
  }
}
for (const t of index) {
  const L = UNSEEN_LEVELS.find(l => l.lang === t.lang && l.id === t.level)
  add(`/unseen/${LANG_PATH[t.lang]}/${t.slug}`, '0.6', `title: '${q(t.title)}', emoji: '📄', kind: 'page', low: true, desc: '${q(`אנסין ${t.lang === 'he' ? 'בעברית' : 'באנגלית'} · ${L.name}`)}', keys: '${q(t.title)} אנסין ${q(L.short)} ${q(t.topic)}'`)
}
add('/dictionary', '0.8', `title: 'מילון לתלמידים — אנגלית לעברית עם הגייה', emoji: '📘', kind: 'tool', desc: 'מקלידים מילה באנגלית, ספרדית, צרפתית, רוסית או ערבית ומקבלים פירוש בעברית והגייה.', keys: 'מילון מילון אנגלית עברית תרגום מילה מילון לילדים מילון לתלמידים הגייה באנגלית'`)
for (const l of 'abcdefghijklmnopqrstuvwxyz') add(`/dictionary/english/${l}`, '0.5', `title: 'מילים באנגלית באות ${l.toUpperCase()}', emoji: '📘', kind: 'page', low: true, desc: 'מילון אנגלית־עברית לתלמידים לפי אות', keys: 'מילים באנגלית באות ${l} מילון ${l.toUpperCase()}'`)
async function patch(file, start, end, body, anchorBefore) {
  const url = new URL(`../${file}`, import.meta.url)
  let text = await readFile(url, 'utf8')
  const block = `${start}\n${body}\n${end}\n`
  if (text.includes(start)) text = text.slice(0, text.indexOf(start)) + block + text.slice(text.indexOf(end) + end.length + 1)
  else { const i = text.indexOf(anchorBefore); if (i < 0) throw new Error(`${file}: anchor not found`); text = text.slice(0, i) + block + text.slice(i) }
  await writeFile(url, text)
}
await patch('public/sitemap-static.xml', '  <!-- unseen:start (scripts/generate-unseen.mjs) -->', '  <!-- unseen:end -->', urls.join('\n'), '  <!-- learn-subjects:start (scripts/generate-learn-subjects.mjs) -->')
await patch('src/data/searchStatic.js', '  // unseen:start (scripts/generate-unseen.mjs)', '  // unseen:end', rows.join('\n'), "  { to: '/learn/reading', title: 'הבנת הנקרא'")
console.log(`generate-unseen: ${index.length} tests, ${urls.length} URLs`)
