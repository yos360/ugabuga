export const dailyRiddle = id => DAILY_RIDDLES.find(r => r.id === id)
export const dailyRiddlePath = r => `/riddles/${r.id}`
// The riddle as one line of text (for descriptions and search)
export const riddleText = r => (r.kind === 'text' || r.kind === 'image' ? r.lines.join(' ') : `${r.title} ${(r.items || r.lines).join(r.kind === 'seq' ? ', ' : ' · ')}`)

// The daily riddles as בוגה לייב questions ("חידות" topic). A told riddle gets its "מי אני?" line too.
export const DAILY_RIDDLE_LIVE_QUESTIONS = DAILY_RIDDLES.filter(r => r.options && r.kind !== 'image').map(r => ({
  id: `dr-${r.id}`,
  q: r.kind === 'text' ? `${riddleText(r)} ${r.ask}` : riddleText(r),
  options: r.options,
  correct: r.options.indexOf(r.answer),
}))
