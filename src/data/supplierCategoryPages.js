// Suppliers for a category page: same stored category, or a keyword in name/tagline/tags.
// Suppliers serving "כל הארץ" show in every area.
export function suppliersForPage(page, list, area = '') {
  return (list || []).filter(s => {
    const text = `${s.name || ''} ${s.tagline || ''} ${(s.tags || []).join(' ')}`
    const inCat = s.category === page.id || page.keywords.some(k => text.includes(k))
    return inCat && (!area || s.area === area || s.area === 'כל הארץ')
  })
}

// "{name} — קוסם ליום הולדת בצפון"
export function supplierPageTitle(s) {
  const page = categoryPageById(s.category)
  const what = page?.short || ''
  const where = s.area ? inArea(s.area) : ''
  return [s.name, [what, where].filter(Boolean).join(' ')].filter(Boolean).join(' — ')
}

const SITE = 'https://ugabuga.co.il'
// LocalBusiness JSON-LD for a supplier card (only fields the supplier filled in).
export function supplierSchema(s) {
  const page = categoryPageById(s.category)
  const sameAs = ['instagram', 'facebook', 'tiktok', 'youtube', 'website'].map(k => s[k]).filter(u => /^https?:\/\//.test(u || ''))
  const areaServed = !s.area ? undefined : s.area === 'כל הארץ'
    ? { '@type': 'Country', name: 'ישראל' }
    : { '@type': 'AdministrativeArea', name: `${s.area}, ישראל` }
  const data = {
    '@context': 'https://schema.org',
    '@type': 'LocalBusiness',
    name: s.name,
    url: `${SITE}/suppliers/${s.slug}`,
    description: (s.about || s.tagline || '').slice(0, 300) || undefined,
    image: s.cover_url || s.logo_url || undefined,
    logo: s.logo_url || undefined,
    telephone: s.phone || undefined,
    areaServed,
    knowsAbout: page?.short,
    sameAs: sameAs.length ? sameAs : undefined,
  }
  return Object.fromEntries(Object.entries(data).filter(([, v]) => v !== undefined && v !== ''))
}
