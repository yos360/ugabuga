// Every word that is a correct partner of `word` in this set (so it's never used as a wrong option).
export function answersFor(set, word) {
  const out = new Set()
  for (const p of set.pairs) { if (p.a === word) out.add(p.b); if (p.b === word) out.add(p.a) }
  return out
}

// Pairs for one level whose words don't repeat (safe for matching/memory games).
export function distinctPairs(pairs, rnd, n) {
  const used = new Set(), out = []
  for (const p of shuffle([...pairs], rnd)) {
    if (used.has(p.a) || used.has(p.b)) continue
    used.add(p.a); used.add(p.b); out.push(p)
    if (out.length === n) break
  }
  return out
}

export function shuffle(arr, rnd = Math.random) {
  for (let i = arr.length - 1; i > 0; i--) { const j = Math.floor(rnd() * (i + 1)); [arr[i], arr[j]] = [arr[j], arr[i]] }
  return arr
}
