// Stable pseudo-random number per (hub, game), used to break ties so each hub orders equal games differently.
function seeded(text) {
  let h = 2166136261
  for (let i = 0; i < text.length; i++) { h ^= text.charCodeAt(i); h = Math.imul(h, 16777619) }
  return (h >>> 0) / 4294967296
}
const has = (list, value) => Array.isArray(list) && list.includes(value)
const dur = g => Number(g.duration_max || g.duration_min || 0)

// Games sorted for one hub: higher score first, ties broken by a per-hub shuffle.
export function hubOrder(games, key, score = () => 0) {
  return games.map(g => ({ g, s: score(g), r: seeded(key + ':' + g.slug) }))
    .sort((a, b) => b.s - a.s || a.r - b.r).map(x => x.g)
}

