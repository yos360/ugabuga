// The label for a card: 'm' boy, 'f' girl, 'both' (שמח / שמחה), with or without nikud.
export function emotionLabel(x, gender, nikud) {
  const m = nikud ? x.mn : x.m, f = nikud ? x.fn : x.f
  if (gender === 'm') return m
  if (gender === 'f') return f
  return m === f ? m : `${m} / ${f}`
}
