// ── letters ──
export const LETTERS = ['א', 'ב', 'ג', 'ד', 'ה', 'ו', 'ז', 'ח', 'ט', 'י', 'כ', 'ל', 'מ', 'נ', 'ס', 'ע', 'פ', 'צ', 'ק', 'ר', 'ש', 'ת']
export const LETTER_SLUGS = { א: 'alef', ב: 'bet', ג: 'gimel', ד: 'dalet', ה: 'he', ו: 'vav', ז: 'zayin', ח: 'het', ט: 'tet', י: 'yod', כ: 'kaf', ל: 'lamed', מ: 'mem', נ: 'nun', ס: 'samekh', ע: 'ayin', פ: 'pe', צ: 'tsadi', ק: 'qof', ר: 'resh', ש: 'shin', ת: 'tav' }
export const LETTER_NAMES = { א: 'אל"ף', ב: 'בי"ת', ג: 'גימ"ל', ד: 'דל"ת', ה: 'ה"א', ו: 'וי"ו', ז: 'זי"ן', ח: 'חי"ת', ט: 'טי"ת', י: 'יו"ד', כ: 'כ"ף', ל: 'למ"ד', מ: 'מ"ם', נ: 'נו"ן', ס: 'סמ"ך', ע: 'עי"ן', פ: 'פ"א', צ: 'צד"י', ק: 'קו"ף', ר: 'רי"ש', ש: 'שי"ן', ת: 'תי"ו' }
const FINALS = { ך: 'כ', ם: 'מ', ן: 'נ', ף: 'פ', ץ: 'צ' }

// Strip niqqud/cantillation and punctuation, fold final letters into their regular form.
export function normalizeHebrew(s) {
  return String(s ?? '').normalize('NFD').replace(/[֑-ׇ]/g, '').replace(/[ךםןףץ]/g, c => FINALS[c]).replace(/[׳״'"`\-־\s]/g, '').toLowerCase()
}
export function firstLetter(name) {
  const c = normalizeHebrew(name).charAt(0)
  return LETTERS.includes(c) ? c : ''
}
export const letterFromSlug = slug => LETTERS.find(l => LETTER_SLUGS[l] === slug) || ''
export const nameLength = name => normalizeHebrew(name).length

// ── normalized data ──
export const BABY_NAMES = RAW.map(([name, en, gender, origin, meaning, source, extra]) => {
  const tags = []
  for (const t of TAGS) {
    if (t === 'תנ"כי' ? origin === 'תנ"כי' : t === 'קצר' ? nameLength(name) <= 3 : extra.includes(t)) tags.push(t)
  }
  return { name, en, slug: en.toLowerCase().replace(/[^a-z]+/g, '-'), gender, origin, meaning, source, tags, letter: firstLetter(name) }
})
export const nameBySlug = slug => BABY_NAMES.find(n => n.slug === slug) || null

// ── filters ──
export const HEBREW_ORIGINS = ['עברי', 'תנ"כי', 'ארמי']
export const ORIGIN_FILTERS = [
  { id: 'hebrew', label: 'עברי', test: n => HEBREW_ORIGINS.includes(n.origin) },
  { id: 'foreign', label: 'לועזי', test: n => !HEBREW_ORIGINS.includes(n.origin) },
]

// gender: 'f' and 'm' include unisex names (they suit both); 'u' = unisex only.
export function matchesGender(n, gender) {
  if (!gender) return true
  return gender === 'u' ? n.gender === 'u' : n.gender === gender || n.gender === 'u'
}

export function matchesQuery(n, q) {
  const h = normalizeHebrew(q)
  if (!h) return true
  return normalizeHebrew(n.name).includes(h) || n.en.toLowerCase().includes(h) || normalizeHebrew(n.meaning).includes(h)
}

export function filterNames(list = BABY_NAMES, { gender = '', letter = '', origin = '', tag = '', q = '' } = {}) {
  const L = letter ? firstLetter(letter) : ''
  const o = ORIGIN_FILTERS.find(f => f.id === origin)
  return list.filter(n => matchesGender(n, gender) && (!L || n.letter === L) && (!o || o.test(n)) && (!tag || n.tags.includes(tag)) && matchesQuery(n, q))
}

export const sortNames = list => [...list].sort((a, b) => a.name.localeCompare(b.name, 'he'))

export function lettersWithNames(gender, min = 1) {
  return LETTERS.filter(l => filterNames(BABY_NAMES, { gender, letter: l }).length >= min)
}

