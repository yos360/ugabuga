export function babyNamePaths() {
  const paths = ['/baby-names', GENDERS.f.path, GENDERS.m.path, GENDERS.u.path]
  for (const g of ['f', 'm']) for (const l of lettersWithNames(g, LETTER_PAGE_MIN)) paths.push(letterPagePath(g, l))
  for (const n of BABY_NAMES) paths.push(namePath(n))
  return paths
}

export const genderText = g => g === 'f' ? 'שם לבת' : g === 'm' ? 'שם לבן' : 'שם יוניסקס — מתאים לבנים ולבנות'

// Up to `count` names that share the most with this one: gender fit, origin, tags, first letter.
export function similarNames(n, count = 6) {
  const scored = BABY_NAMES.filter(o => o !== n).map(o => {
    let s = 0
    if (o.gender === n.gender) s += 3; else if (o.gender === 'u' || n.gender === 'u') s += 1; else s -= 5
    if (o.origin === n.origin) s += 2
    for (const t of n.tags) if (o.tags.includes(t)) s += t === 'קצר' ? 1 : 2
    if (o.letter === n.letter) s += 2
    return { o, s }
  })
  return scored.sort((a, b) => b.s - a.s || a.o.name.localeCompare(b.o.name, 'he')).slice(0, count).map(x => x.o)
}

const plainMeaning = m => m.replace(/\s+/g, ' ').trim()
function clip(text, max) {
  if (text.length <= max) return text
  const cut = text.slice(0, max - 1)
  return cut.slice(0, cut.lastIndexOf(' ')).replace(/[,.;:—–\s]+$/, '') + '…'
}

export function nameTitle(n) { return `משמעות השם ${n.name} — מקור, פירוש ושמות דומים` }

// 120–160 chars, for the name page meta description.
export function nameDescription(n) {
  const tail = ` מקור ${n.origin}, ${genderText(n.gender).split(' — ')[0]}, איך כותבים באנגלית ושמות דומים.`
  const head = `משמעות השם ${n.name}: `
  let d = head + clip(plainMeaning(n.meaning), 160 - head.length - tail.length) + tail
  for (const pad of [' רעיונות לשמות נוספים ושמירה לרשימה.', ' בחינם, בעברית.']) if (d.length < 120) d += pad
  if (d.length > 160) d = clip(d, 160)
  return d
}

export function nameFaq(n) {
  const faq = [
    { q: `מה המשמעות של השם ${n.name}?`, a: `${n.meaning} מקור השם: ${n.origin}.` },
    { q: `האם ${n.name} הוא שם לבן או לבת?`, a: n.gender === 'u' ? `${n.name} הוא שם יוניסקס — נותנים אותו גם לבנים וגם לבנות.` : `${n.name} הוא ${genderText(n.gender)}.` },
    { q: `איך כותבים ${n.name} באנגלית?`, a: `הכתיב הנפוץ הוא ${n.en}. באנגלית יש לעיתים כמה כתיבים לאותו שם — כדאי לבחור כתיב אחד ולהקפיד עליו בדרכון ובמסמכים.` },
  ]
  if (n.source && n.origin === 'תנ"כי') faq.splice(2, 1, { q: `איפה מופיע השם ${n.name} בתנ"ך?`, a: `השם ${n.name} מופיע בתנ"ך — ${n.source}. ${n.meaning}` })
  return faq
}

