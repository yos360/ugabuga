// הרשומה האחרונה שאינה גבוהה מהשנה שהוזנה. מתחת לשנה הראשונה: אין עדיין שם.
export function anniversaryInfo(years) {
  const n = Math.floor(Number(years))
  if (!Number.isFinite(n) || n < 1) return null
  const exact = ANNIVERSARY_YEARS.find(r => r.y === n) || null
  const below = [...ANNIVERSARY_YEARS].reverse().find(r => r.y <= n)
  const next = ANNIVERSARY_YEARS.find(r => r.y > n) || null
  return { years: n, exact, below, next }
}

