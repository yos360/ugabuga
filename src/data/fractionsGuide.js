// The fraction wall: one row per denominator, all rows the same length.
export const WALL_ROWS = [1, 2, 3, 4, 5, 6, 8, 10, 12]

export function gcd(a, b) { a = Math.abs(a); b = Math.abs(b); while (b) [a, b] = [b, a % b]; return a || 1 }
export function lcm(a, b) { return (a / gcd(a, b)) * b }

// Compare a/b with c/d through the smallest common denominator, for the on-page comparison tool.
export function compareFractions(a, b, c, d) {
  const L = lcm(b, d), x = a * (L / b), y = c * (L / d)
  return { L, x, y, sign: x > y ? '>' : x < y ? '<' : '=' }
}

export function simplify(n, d) { const g = gcd(n, d); return [n / g, d / g] }
