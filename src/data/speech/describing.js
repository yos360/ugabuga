const PRON = { m: 'הוא', f: 'היא' }
const LO = { m: 'לו', f: 'לה' }
const OTO = { m: 'אותו', f: 'אותה' }
const ASUY = { m: 'עשוי', f: 'עשויה' }

// "קמח, מים ושמרים" / "עץ, פלסטיק או מתכת"
export function joinList(words, or = false) {
  if (words.length < 2) return words[0] || ''
  return `${words.slice(0, -1).join(', ')} ${or ? 'או' : 'ו'}${or ? ' ' : ''}${words[words.length - 1]}`
}
export const matText = it => it.mat ? joinList(it.mat, it.or) : null

// The short value of a star point for an item (a chip label), or null when the point doesn't fit.
export function value(it, dim) {
  if (dim === 'group') return CATS[it.cat].one
  if (dim === 'mat') return matText(it)
  return it[dim] || null
}

// One full sentence per star point, in the item's grammatical gender.
export function sentence(it, dim) {
  const g = it.g
  switch (dim) {
    case 'group': return `${it.t} ${PRON[g]} ${CATS[it.cat].one}.`
    case 'look': return `${PRON[g]} ${it.look}.`
    case 'mat': return it.mat ? `${PRON[g]} ${ASUY[g]} ${it.or ? joinList(it.mat.map(m => `מ${m}`), true) : `מ${joinList(it.mat)}`}.` : null
    case 'parts': return it.parts ? `יש ${LO[g]} ${it.parts}.` : null
    case 'place': return `מוצאים ${OTO[g]} ${it.place}.`
    case 'use': return `${it.use}.`
    case 'more': return `${it.more}.`
    default: return null
  }
}
export const describe = (it, dims = DIMS.map(d => d.id)) => dims.map(d => sentence(it, d)).filter(Boolean)

// Why a star point is empty, for the builder and the word map.
export function emptyNote(it, dim) {
  const f = it.g === 'f'
  if (dim === 'mat') {
    const why = ['animal', 'insect'].includes(it.cat) ? (f ? 'היא חיה' : 'הוא חי')
      : ['fruit', 'veg', 'plant'].includes(it.cat) ? (f ? 'היא גדלה בטבע' : 'הוא גדל בטבע')
        : (f ? 'היא מגיעה מהטבע' : 'הוא מגיע מהטבע')
    return `${it.t} לא ${f ? '„עשויה”' : '„עשוי”'} ממשהו — ${why}. מדלגים על הפינה הזאת.`
  }
  if (dim === 'parts') return `ל${it.t} אין ממש חלקים. מדלגים על הפינה הזאת.`
  return ''
}

export function shuffleWith(list, rand = Math.random) {
  const a = [...list]
  for (let i = a.length - 1; i > 0; i--) { const j = Math.floor(rand() * (i + 1)); [a[i], a[j]] = [a[j], a[i]] }
  return a
}

// Builder step: the item's own value and two values of other items from other categories
// (same grammatical gender first, so the chips read naturally). Each option names its owner.
export function builderOptions(it, dim, rand = Math.random) {
  const own = value(it, dim)
  if (!own) return null
  const pool = shuffleWith(ITEMS.filter(o => o.cat !== it.cat && value(o, dim) && value(o, dim) !== own), rand)
  const sorted = [...pool.filter(o => o.g === it.g), ...pool.filter(o => o.g !== it.g)]
  const picked = []
  for (const o of sorted) if (picked.length < 2 && !picked.some(p => value(p, dim) === value(o, dim))) picked.push(o)
  return shuffleWith([{ label: own, owner: it }, ...picked.map(o => ({ label: value(o, dim), owner: o }))], rand)
}

// "Who am I?" round: the target and five other pictures — two from the same or a close
// category, so the first clues still leave a real choice.
export function riddleRound(rand = Math.random, prevT) {
  const item = shuffleWith(ITEMS.filter(i => i.t !== prevT), rand)[0]
  const same = shuffleWith(ITEMS.filter(i => i !== item && i.cat === item.cat), rand).slice(0, 2)
  const rest = shuffleWith(ITEMS.filter(i => i !== item && !same.includes(i)), rand).slice(0, 5 - same.length)
  return { item, choices: shuffleWith([item, ...same, ...rest], rand) }
}

