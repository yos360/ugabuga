// Comparison helpers for any two items: the shared category or material, if any.
export function sameFacts(a, b) {
  const both = a.g === 'f' && b.g === 'f' ? 'שתיהן' : 'שניהם'
  const out = []
  if (a.cat === b.cat) out.push(`${both} ${CATS[a.cat].name}.`)
  const mats = (a.mat || []).filter(m => (b.mat || []).includes(m))
  if (mats.length) out.push(`${both} ${both === 'שתיהן' ? 'עשויות' : 'עשויים'} מ${joinList(mats)}.`)
  return out
}

