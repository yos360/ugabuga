// The words that tie a story together: קודם … אחר כך … ואז … בסוף.
const MIDDLE = ['אחר כך', 'ואז', 'אחרי זה', 'אחר כך']
export function connector(i, n) {
  if (i === 0) return 'קודם'
  if (i === n - 1) return 'בסוף'
  return MIDDLE[(i - 1) % MIDDLE.length]
}
export function storyText(seq) {
  const n = seq.steps.length
  return seq.steps.map((s, i) => `${connector(i, n)} ${s.t}`).join(' ')
}
