const has = (text, words, phrase) => phrase.includes(' ') ? text.includes(` ${phrase} `) : words.has(phrase)

export function findBugaPediaSuperlative(question) {
  const text = ` ${tidy(question)} `
  const raw = text.trim().split(' ')
  const words = new Set([...raw, ...raw.map(stripHe)])
  if (!MARKERS.some(marker => words.has(marker))) return null
  const land = LAND.some(word => words.has(word))
  const adjectives = Object.keys(ADJECTIVES).filter(key => ADJECTIVES[key].some(form => words.has(form)))
  const nouns = Object.keys(NOUNS).filter(key => NOUNS[key].some(form => has(text, words, form)))
  for (const noun of nouns) for (const adjective of adjectives) {
    const fact = FACTS.find(([n, a, landOnly]) => n === noun && a === adjective && landOnly === land)
      || FACTS.find(([n, a]) => n === noun && a === adjective)
    if (fact) {
      const [, , , title, extract, term] = fact
      return { id: `superlative-${noun}-${adjective}${land ? '-land' : ''}`, title, extract, url: wiki(term), image: '', verified: true, sourceLabel: 'תשובה בדוקה של בוגה־פדיה', linkLabel: 'לקריאה נוספת בוויקיפדיה ↗' }
    }
  }
  return null
}
