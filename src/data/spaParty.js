export function shoppingList(kids) {
  const n = Math.max(1, Math.round(kids))
  const rows = SPA_SHOPPING.map(s => {
    const qty = s.perKids ? Math.ceil(n / s.perKids) : 1
    return { ...s, qty, cost: Math.round(qty * s.price) }
  })
  return { rows, total: rows.reduce((t, r) => t + r.cost, 0) }
}
