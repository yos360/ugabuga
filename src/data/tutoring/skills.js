// The tutoring plans (/tutoring): what a child can struggle with, in a parent's words, and the ladder of steps
// that rebuilds it. A step knows the grade its material belongs to, so a fifth-grader who is stuck on fractions
// can go back to fourth-grade material; a step with no grade works at any grade (a reading strategy, say).
//
// Step: { title, how, grade?, link? }
//   how   what the parent does with the child, in two or three sentences
//   link  the practice on the site, same shapes as the teachers' planner (src/data/planner/schema.js), plus a
//         grade on math-topic links. 'reading', 'vocab-auto' and 'unseen-auto' pick a text or a unit by the
//         child's grade and the session, see ./plan.js
const m = (grade, slug, title, how) => ({ grade, title, how, link: { type: 'math-topic', grade, slug } })
const l = (grade, slug, title, how) => ({ grade, title, how, link: { type: 'lesson', slug: `lashon/${slug}` } })
const g = (grade, slug, title, how) => ({ grade, title, how, link: { type: 'grammar', slug } })
const p = (grade, slug, title, how, label) => ({ grade, title, how, link: { type: 'page', slug, label } })
const r = (title, how) => ({ title, how, link: { type: 'reading' } })
const d = (grade, set, title, how) => ({ grade, title, how, link: { type: 'dictation', set } })

