// Visual card sets for kindergarten and special education: regulation, senses, communication,
// daily schedule, help requests and animal walks. Every text has a plain form (t) and a
// vocalised form (n). Gendered texts carry m / f / b (both: "צריך/ה").
// icon: an emoji, or "svg:<name>" for a small drawing in SensoryCommunicationCards.jsx.

const L = (t, n) => ({ t, n })
const G = (m, f, b) => ({ m, f, b })

export const pick = (text, { nikud, gender }) => {
  const v = text.m ? text[gender] || text.b : text
  return nikud ? v.n : v.t
}

