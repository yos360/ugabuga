export const BUYING_BY_ID = Object.fromEntries(BUYING_GUIDES.map(g => [g.id, g]))
export const buyingPath = id => `${BUYING_ROOT}/${id}`

// JSON-LD for a guide page: Article + FAQPage + ItemList (the item types, then real products by
// name/url only). No Product/Offer/AggregateRating/price fields, by design.
export function buyingGuideSchemas(guide, products = []) {
  const url = SITE + buyingPath(guide.id)
  const org = { '@type': 'Organization', name: 'עוגה בוגה', url: SITE }
  const article = {
    '@context': 'https://schema.org',
    '@type': 'Article',
    headline: guide.title,
    description: guide.description,
    inLanguage: 'he',
    datePublished: BUYING_UPDATED,
    dateModified: BUYING_UPDATED,
    author: org,
    publisher: { ...org, logo: { '@type': 'ImageObject', url: `${SITE}/og-image.png` } },
    image: `${SITE}/og-image.png`,
    mainEntityOfPage: url,
    about: guide.audience,
  }
  const faq = {
    '@context': 'https://schema.org',
    '@type': 'FAQPage',
    mainEntity: guide.faq.map(f => ({ '@type': 'Question', name: f.q, acceptedAnswer: { '@type': 'Answer', text: f.a } })),
  }
  const list = {
    '@context': 'https://schema.org',
    '@type': 'ItemList',
    name: guide.title,
    numberOfItems: guide.items.length + products.length,
    itemListElement: [
      ...guide.items.map((it, i) => ({ '@type': 'ListItem', position: i + 1, name: it.name, description: it.why })),
      ...products.map((p, i) => ({ '@type': 'ListItem', position: guide.items.length + i + 1, name: p.name, url: p.url })),
    ],
  }
  return [article, faq, list]
}

export function buyingHubSchemas() {
  return [{
    '@context': 'https://schema.org',
    '@type': 'ItemList',
    name: BUYING_HUB.title,
    numberOfItems: BUYING_GUIDES.length,
    itemListElement: BUYING_GUIDES.map((g, i) => ({ '@type': 'ListItem', position: i + 1, name: g.title, url: SITE + buyingPath(g.id) })),
  }]
}
