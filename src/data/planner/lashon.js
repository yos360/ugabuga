const TYPES = { l: 'lesson', r: 'heb-reading', b: 'booklet' }
// 'l:root r:snail b:spelling' → [{ type: 'lesson', slug: 'lashon/root' }, ...]
const L = s => s.split(' ').filter(Boolean).map(x => {
  const i = x.indexOf(':')
  const k = x.slice(0, i)
  const slug = x.slice(i + 1)
  return { type: TYPES[k], slug: k === 'l' ? `lashon/${slug}` : slug }
})
const unit = (id, title, hours, goals, concepts, steps) => ({
  id, title, hours, goals, concepts,
  steps: steps.map(([t, goal, activity, practice, links = '']) => ({ title: t, goal, activity, practice, links: L(links) })),
})

