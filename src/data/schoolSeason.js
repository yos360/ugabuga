export const MAX_QTY = 99
export const MAX_CUSTOM = 30
export const normalizeQty = v => clampInt(v, 0, MAX_QTY, 1)
export const levelById = id => SUPPLY_LEVELS.find(l => l.id === id) || SUPPLY_LEVELS[1]

// State per level: { [itemId]: { qty, done } } plus custom: [{ id, name, qty, done }].
export function initialSupplyState(level) {
  return { items: Object.fromEntries(level.items.map(i => [i.id, { qty: i.qty, done: false }])), custom: [] }
}

// Merge a saved state onto the defaults, dropping anything malformed.
export function restoreSupplyState(level, saved) {
  const base = initialSupplyState(level)
  if (!saved || typeof saved !== 'object') return base
  for (const i of level.items) {
    const s = saved.items?.[i.id]
    if (s && typeof s === 'object') base.items[i.id] = { qty: normalizeQty(s.qty), done: !!s.done, ...(s.removed ? { removed: true } : {}) }
  }
  if (Array.isArray(saved.custom)) {
    base.custom = saved.custom.slice(0, MAX_CUSTOM)
      .map(c => ({ id: String(c?.id || ''), name: cleanItem(c?.name), qty: normalizeQty(c?.qty), done: !!c?.done }))
      .filter(c => c.id && c.name)
  }
  return base
}

export const MAX_ITEM = 40
export function cleanItem(s) { return String(s ?? '').replace(/[<>{}]/g, '').replace(/\s+/g, ' ').trim().slice(0, MAX_ITEM) }

// The rows shown/printed for a level: standard items (unless removed) and then custom ones.
export function supplyRows(level, state) {
  const std = level.items.filter(i => !state.items[i.id]?.removed).map(i => ({ id: i.id, name: i.name, qty: state.items[i.id]?.qty ?? i.qty, done: !!state.items[i.id]?.done, custom: false }))
  return [...std, ...state.custom.map(c => ({ ...c, custom: true }))]
}

export function supplyListText(level, state, { onlyMissing = false } = {}) {
  const rows = supplyRows(level, state).filter(r => r.qty > 0 && (!onlyMissing || !r.done))
  const head = `🎒 רשימת ציוד — ${level.label}${onlyMissing ? ' (מה שעוד חסר)' : ''}`
  const body = rows.map(r => `${r.done ? '✅' : '⬜'} ${r.name}${r.qty > 1 ? ` × ${r.qty}` : ''}`)
  return [head, ...body, '', 'כדאי לבדוק מול הרשימה שקיבלתם מבית הספר.'].join('\n')
}

