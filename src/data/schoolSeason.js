// ── group-gift calculator ─────────────────────────
export const MAX_FAMILIES = 60
export const MAX_PER_FAMILY = 1000

export function clampInt(v, min, max, fallback = min) {
  const n = Math.round(Number(v))
  if (!Number.isFinite(n)) return fallback
  return Math.min(max, Math.max(min, n))
}

// Split a whole-shekel total by weights; parts are whole shekels and always add up to the total
// (largest-remainder rounding).
export function splitByWeights(total, weights) {
  const t = Math.max(0, Math.round(Number(total) || 0))
  const w = weights.map(x => Math.max(0, Number(x) || 0))
  const sum = w.reduce((a, b) => a + b, 0)
  if (!w.length) return []
  if (sum === 0) return w.map(() => 0)
  const raw = w.map(x => (t * x) / sum)
  const parts = raw.map(Math.floor)
  let left = t - parts.reduce((a, b) => a + b, 0)
  const order = raw.map((r, i) => [r - Math.floor(r), i]).sort((a, b) => b[0] - a[0] || a[1] - b[1])
  for (let k = 0; left > 0; k = (k + 1) % order.length) { if (w[order[k][1]] > 0) { parts[order[k][1]]++; left-- } }
  return parts
}

// families × perFamily = total, then divided between the recipients by weight.
export function groupGift({ families, perFamily, recipients }) {
  const f = clampInt(families, 1, MAX_FAMILIES, 25)
  const p = clampInt(perFamily, 0, MAX_PER_FAMILY, 0)
  const total = f * p
  const list = (recipients || []).filter(r => r && r.on !== false)
  const amounts = splitByWeights(total, list.map(r => r.weight))
  return { families: f, perFamily: p, total, shares: list.map((r, i) => ({ label: r.label, weight: r.weight, amount: amounts[i] })) }
}

// How much each family pays to reach a target sum (rounded up to a whole shekel).
export function perFamilyFor(target, families) {
  const f = clampInt(families, 1, MAX_FAMILIES, 1)
  const t = Math.max(0, Number(target) || 0)
  return Math.ceil(t / f)
}

