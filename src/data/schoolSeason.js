// Clock times for the plan from a start time "HH:MM".
export function scheduleFrom(start, list) {
  const m = /^(\d{1,2}):(\d{2})$/.exec(String(start || ''))
  let t = m ? Math.min(23, +m[1]) * 60 + Math.min(59, +m[2]) : 17 * 60
  const fmt = x => `${String(Math.floor(x / 60) % 24).padStart(2, '0')}:${String(x % 60).padStart(2, '0')}`
  return list.map(s => { const at = fmt(t); t += s.min; return { ...s, at } })
}

