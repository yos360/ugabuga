// Gift text for WhatsApp to the parents' group.
export function groupGiftMessage({ total, perFamily, families, shares }, occasion = 'מתנה לצוות לסוף השנה') {
  const lines = [
    `🎁 ${occasion}`,
    `${families} משפחות × ${perFamily} ₪ = ${total} ₪`,
    ...shares.map(s => `• ${s.label}: ${s.amount} ₪`),
    'מי שמתקשה בסכום — אפשר לפנות בפרטי, בלי שאלות 💛',
  ]
  return lines.join('\n')
}

// ── names on printables ─────────────────────────
export const MAX_NAME = 24
export function cleanName(s) {
  return String(s ?? '').replace(/[<>{}[\]\\]/g, '').replace(/\s+/g, ' ').trim().slice(0, MAX_NAME)
}
// One name per line (or comma), cleaned, de-duplicated, capped — for a whole class of certificates.
export const MAX_CERTS = 40
export function parseNames(text) {
  const seen = new Set(), out = []
  for (const part of String(text ?? '').split(/[\n,،]+/)) {
    const n = cleanName(part)
    if (n && !seen.has(n)) { seen.add(n); out.push(n) }
    if (out.length >= MAX_CERTS) break
  }
  return out
}

