export function totalMinutes(c) { return (c.time.prep || 0) + (c.time.cook || 0) + (c.time.chill || 0) }

// ISO 8601 duration for schema.org: 95 → "PT1H35M"
export function isoDuration(min) {
  const m = Math.max(0, Math.round(min || 0))
  const h = Math.floor(m / 60), r = m % 60
  return 'PT' + (h ? `${h}H` : '') + (r || !h ? `${r}M` : '')
}

export function minutesLabel(min) {
  const h = Math.floor(min / 60), r = min % 60
  if (!h) return `${r} דק׳`
  const hs = h === 1 ? 'שעה' : h === 2 ? 'שעתיים' : `${h} שעות`
  return r ? `${hs} ו־${r} דק׳` : hs
}

export const isParveFriendly = c => c.kosher === 'parve' || c.kosher === 'dairy-or-parve'

export function matchesTag(c, tag) {
  if (!tag) return true
  if (tag === 'parve') return isParveFriendly(c)
  return c.tags.includes(tag)
}

