const i = (q, u, name, note) => ({ q, u, name, ...(note ? { note } : {}) })
const t = (name, note) => ({ q: null, u: '', name, ...(note ? { note } : {}) })

const FRACTIONS = [[0, ''], [0.25, '¼'], [1 / 3, '⅓'], [0.5, '½'], [2 / 3, '⅔'], [0.75, '¾'], [1, '']]

// 1.75 → "1¾", 0.5 → "½", 2 → "2", 2.2 → "2.2"
export function formatQty(q) {
  if (q == null) return ''
  const whole = Math.floor(q + 1e-9)
  const frac = q - whole
  let best = null
  for (const [v, s] of FRACTIONS) if (Math.abs(frac - v) < 0.04) { best = [v, s]; break }
  if (!best) return String(Math.round(q * 10) / 10)
  const w = best[0] === 1 ? whole + 1 : whole
  if (!w) return best[1] || '0'
  return `${w}${best[1]}`
}

export function scaleQty(q, u, factor) {
  if (q == null) return null
  const v = q * factor
  if (u === 'g' || u === 'ml') return v >= 50 ? Math.round(v / 5) * 5 : Math.round(v)
  return v
}

export function formatIngredient(item, factor = 1) {
  if (item.q == null) return item.name + (item.note ? ` (${item.note})` : '')
  const q = scaleQty(item.q, item.u, factor)
  const [one, many] = UNITS[item.u] || ['', '']
  const unit = q > 1 ? many : one
  return [formatQty(q), unit, item.name].filter(Boolean).join(' ') + (item.note ? ` (${item.note})` : '')
}

