export const CAKE_SLUGS = CAKES.map(c => c.slug)
export const getCake = slug => CAKES.find(c => c.slug === slug) || null
export const cakePath = c => `${CAKES_HUB_PATH}/${typeof c === 'string' ? c : c.slug}`
export const CAKE_PATHS = [CAKES_HUB_PATH, ...CAKES.map(cakePath)]
export const relatedCakes = c => (c.related || []).map(getCake).filter(Boolean)
export const cakeShortTitle = c => c.shortTitle || c.title

export function allergenLabels(c) { return c.allergens.map(a => ALLERGENS[a]).filter(Boolean) }

export function ingredientLines(c, factor = 1) {
  return c.ingredients.flatMap(g => g.items.map(it => formatIngredient(it, factor)))
}

export function stepLines(c) { return c.steps.flatMap(g => g.items) }

// schema.org Recipe for kind === 'recipe'; null for guides.
export function recipeSchema(c) {
  if (!c || c.kind !== 'recipe') return null
  const url = `${SITE}${cakePath(c)}`
  const s = {
    '@context': 'https://schema.org',
    '@type': 'Recipe',
    'name': c.title,
    'description': c.description,
    'image': [`${SITE}/og-image.png`],
    'url': url,
    'inLanguage': 'he',
    'author': { '@type': 'Organization', 'name': 'UGABUGA', 'url': SITE },
    'recipeCategory': 'עוגות יום הולדת',
    'recipeCuisine': 'ישראלית',
    'keywords': ['עוגת יום הולדת', ...c.tags.map(id => CAKE_TAGS.find(x => x.id === id)?.label).filter(Boolean)].join(', '),
    'recipeYield': c.yieldText,
    'prepTime': isoDuration(c.time.prep),
    'totalTime': isoDuration(totalMinutes(c)),
    'recipeIngredient': ingredientLines(c),
    'recipeInstructions': c.steps.flatMap(g => g.items).map((text, n) => ({ '@type': 'HowToStep', 'position': n + 1, 'text': text, 'url': `${url}#step-${n + 1}` })),
  }
  if (c.time.cook) s.cookTime = isoDuration(c.time.cook)
  if (c.kosher === 'parve' && c.tags.includes('vegan')) s.suitableForDiet = 'https://schema.org/VeganDiet'
  else if (c.tags.includes('gluten-free')) s.suitableForDiet = 'https://schema.org/GlutenFreeDiet'
  return s
}

