export const ALL_COMMENTS = COMMENT_GROUPS.flatMap(g => g.items.map(i => ({ ...i, group: g.id })))

const BY_ID = new Map(ALL_COMMENTS.map(c => [c.id, c]))
export const findComment = id => BY_ID.get(id)

// The sentence for a boy ('m') or a girl ('f'), written by a female ('f') or male ('m') teacher:
// {t:female|male} marks the teacher's own words. The name goes only into {name}; with no name the opener
// reads "תלמיד יקר," / "תלמידה יקרה," and other placeholders are dropped.
export function sentence(c, gender, name = '', teacher = 'f') {
  const raw = (gender === 'f' ? c.f : c.m).replace(/\{t:([^|}]+)\|([^}]+)\}/g, (_, f, m) => (teacher === 'm' ? m : f))
  if (!raw.includes('{name}')) return raw
  const n = name.trim()
  if (n) return raw.replace('{name}', n)
  if (c.id === 'open-1') return gender === 'f' ? 'תלמידה יקרה,' : 'תלמיד יקר,'
  return raw.replace(', {name},', ',').replace('{name}', '').trim()
}

// The whole evaluation: an opener that ends in a comma goes on its own line, the rest flow as one paragraph.
export function composeComment(ids, gender, name = '', teacher = 'f') {
  const parts = ids.map(findComment).filter(Boolean).map(c => sentence(c, gender, name, teacher))
  const head = [], body = []
  for (const p of parts) (p.endsWith(',') && body.length === 0 ? head : body).push(p)
  return [head.join(' '), body.join(' ')].filter(Boolean).join('\n')
}
