// Random joke, never the same as `exceptN` when there is a choice.
export function randomJoke(list = KERESH_JOKES, exceptN, rnd = Math.random) {
  if (!list.length) return null
  const pool = list.length > 1 ? list.filter(j => j.n !== exceptN) : list
  return pool[Math.floor(rnd() * pool.length)]
}

