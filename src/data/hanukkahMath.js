// ---- The dreidel game ----
// Gematria of the dreidel letters (a fact): נ=50, ג=3, ה=5, ש=300, פ=80.
export const GEMATRIA = { 'נ': 50, 'ג': 3, 'ה': 5, 'ש': 300, 'פ': 80 }
export const DREIDEL = ['נ', 'ג', 'ה', 'ש']
// The multiplication game uses its own small values, so it practises the 2–5 times tables.
export const TIMES_VALUES = { 'נ': 2, 'ג': 3, 'ש': 4, 'ה': 5 }

export const GAME_MODES = [
  { id: 'pot', label: 'חיבור וחיסור', grades: 'א׳–ב׳', rule: 'משחק הסביבון הרגיל: נ — לא קורה כלום, ג — לוקחים את כל הקופה, ה — לוקחים חצי מהקופה, ש — שמים 2 בקופה. מחשבים כמה מטבעות יש לכם עכשיו.' },
  { id: 'times', label: 'כפל', grades: 'ג׳–ד׳', rule: 'לכל אות יש ערך: נ=2, ג=3, ש=4, ה=5. כופלים את ערך האות במספר הערב של חנוכה.' },
  { id: 'gematria', label: 'גימטריה', grades: 'ה׳–ו׳', rule: 'מסובבים שלוש פעמים ומחברים את ערכי האותיות בגימטריה: נ=50, ג=3, ה=5, ש=300.' },
]

const pick = (rng, list) => list[Math.floor(rng() * list.length)]
const int = (rng, lo, hi) => lo + Math.floor(rng() * (hi - lo + 1))

// One round of the game: { letters, q, a, sol }. `rng` returns [0,1) like Math.random.
export function gameQuestion(mode, rng = Math.random) {
  if (mode === 'times') {
    const letter = pick(rng, DREIDEL), night = int(rng, 2, 8), v = TIMES_VALUES[letter]
    return { letters: [letter], q: `ערב ${night} של חנוכה, ויצא ${letter} (${v}). כמה נקודות קיבלתם? ${v} × ${night} = ?`, a: v * night, sol: `${v} × ${night} = ${v * night}` }
  }
  if (mode === 'gematria') {
    const letters = [pick(rng, DREIDEL), pick(rng, DREIDEL), pick(rng, DREIDEL)]
    const vals = letters.map(l => GEMATRIA[l]), sum = vals.reduce((s, x) => s + x, 0)
    return { letters, q: `יצאו ${letters.join(', ')}. מה סכום הגימטריה? ${vals.join(' + ')} = ?`, a: sum, sol: `${vals.join(' + ')} = ${sum}` }
  }
  // 'pot': numbers stay within 20, the pot is always even so half of it is whole.
  const letter = pick(rng, ['ג', 'ה', 'ש']), mine = int(rng, 3, 10), pot = 2 * int(rng, 2, 5)
  if (letter === 'ג') return { letters: [letter], q: `יש לכם ${mine} מטבעות ובקופה ${pot}. יצא ג׳ — לוקחים את כל הקופה. כמה מטבעות יש לכם עכשיו?`, a: mine + pot, sol: `${mine} + ${pot} = ${mine + pot}` }
  if (letter === 'ה') return { letters: [letter], q: `יש לכם ${mine} מטבעות ובקופה ${pot}. יצא ה׳ — לוקחים חצי מהקופה. כמה מטבעות יש לכם עכשיו?`, a: mine + pot / 2, sol: `חצי מ־${pot} הוא ${pot / 2}. ${mine} + ${pot / 2} = ${mine + pot / 2}` }
  return { letters: [letter], q: `יש לכם ${mine} מטבעות. יצא ש׳ — שמים 2 מטבעות בקופה. כמה מטבעות נשארו לכם?`, a: mine - 2, sol: `${mine} − 2 = ${mine - 2}` }
}

// Accepts "1,080", " 26 ", "26.0" and "25%" as the same number.
export function parseAnswer(text) {
  const clean = String(text).replace(/[,\s%₪]/g, '')
  if (!/^-?\d+(\.\d+)?$/.test(clean)) return null
  return Number(clean)
}
