export const storyWords = paragraphs => paragraphs.join(' ').split(/\s+/).filter(Boolean).length

// Splits a story's paragraphs into two printed pages of roughly equal word count.
export function splitForPrint(paragraphs) {
  const total = storyWords(paragraphs)
  let run = 0, i = 0
  const first = []
  while (i < paragraphs.length - 1 && run < total / 2) { run += storyWords([paragraphs[i]]); first.push(paragraphs[i]); i++ }
  return [first, paragraphs.slice(i)]
}
