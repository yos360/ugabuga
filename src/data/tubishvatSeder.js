export const FAMILY_RIDDLES = 4

// The seder for one version: family (short, no roles) or class (with roles, extra passages, all riddles).
export function buildSeder(version) {
  const cls = version === 'class'
  return STEPS.map(s => ({
    ...s,
    lines: cls && s.more ? [...s.text, ...s.more] : s.text,
    roleName: cls ? ROLES.find(r => r.id === s.role)?.name : undefined,
    riddles: s.kind === 'riddles' ? RIDDLES.slice(0, cls ? RIDDLES.length : FAMILY_RIDDLES) : undefined,
    talk: s.kind === 'riddles' && cls ? TALK_QUESTIONS : undefined,
  }))
}

