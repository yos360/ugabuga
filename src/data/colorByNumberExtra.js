// More color-by-number pictures: subjects people search for, and mandalas built from the same cells.
// Original drawings only: no characters from films, games or books.
// Same format as colorByNumber.js, with two shortcuts for regular shapes:
//   mirror(rows): each row is the left half; the right half is its reflection.
//   mandala(rows): an eighth of a mandala. Row a is `a` cells out from the center and holds a + 1
//   cells, from the axis to the diagonal; the rest of the circle is reflected from it.

const mirror = rows => rows.map(r => r + [...r].reverse().join(''))
const pad = (rows, fill = '.') => { const w = Math.max(...rows.map(r => r.length)); return rows.map(r => r.padEnd(w, fill)) }

function mandala(slice) {
  const n = slice.length, cell = (a, b) => (a >= b ? slice[a][b] : slice[b][a])
  const half = Array.from({ length: n }, (_, y) => Array.from({ length: n }, (_, x) => cell(n - 1 - y, n - 1 - x)).join(''))
  const top = mirror(half)
  return [...top, ...[...top].reverse()]
}
// legend order: the order the colors first appear, from the center out
const colorsOf = slice => [...new Set(slice.join('').replace(/\./g, ''))].join('')
const mandalaPicture = (slug, name, level, blurb, slice) => ({ slug, name, emoji: '🌀', level, colors: colorsOf(slice), theme: 'mandala', blurb, rows: mandala(slice) })

