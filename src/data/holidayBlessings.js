// Hebrew numeral with geresh / gershayim: 1 → א׳, 15 → ט״ו, 34 → ל״ד.
export function heNum(n) {
  const ones = ['', 'א', 'ב', 'ג', 'ד', 'ה', 'ו', 'ז', 'ח', 'ט'], tens = ['', 'י', 'כ', 'ל', 'מ', 'נ', 'ס', 'ע', 'פ', 'צ'], hundreds = ['', 'ק', 'ר', 'ש', 'ת']
  let s = hundreds[Math.floor(n / 100)] || ''
  const r = n % 100
  s += r === 15 ? 'טו' : r === 16 ? 'טז' : tens[Math.floor(r / 10)] + ones[r % 10]
  return s.length === 1 ? s + '׳' : s.slice(0, -1) + '״' + s.slice(-1)
}

// 'Leviticus 22:26-23:44' → { book, from: [22, 26], to: [23, 44] }; 'Ezekiel 3:12' → single verse.
export function parseRef(ref) {
  const m = /^(.+) (\d+):(\d+)(?:-(?:(\d+):)?(\d+))?$/.exec(ref)
  if (!m || !BOOKS[m[1]]) throw new Error('bad ref: ' + ref)
  const from = [+m[2], +m[3]]
  const to = m[5] ? [m[4] ? +m[4] : from[0], +m[5]] : from
  return { book: m[1], from, to }
}

export function heRef(ref) {
  const { book, from, to } = parseRef(ref)
  const start = `${BOOKS[book]} ${heNum(from[0])}, ${heNum(from[1])}`
  if (from[0] === to[0] && from[1] === to[1]) return start
  return from[0] === to[0] ? `${start} עד ${heNum(to[1])}` : `${start} עד ${heNum(to[0])}, ${heNum(to[1])}`
}

export function sefariaUrl(ref) {
  const { book, from, to } = parseRef(ref)
  const b = book.replace(/ /g, '_')
  const range = from[0] === to[0] && from[1] === to[1] ? `${from[0]}.${from[1]}` : from[0] === to[0] ? `${from[0]}.${from[1]}-${to[1]}` : `${from[0]}.${from[1]}-${to[0]}.${to[1]}`
  return `https://www.sefaria.org.il/${b}.${range}?lang=he`
}

