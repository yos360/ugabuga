// ── math inside Hebrew text ───────────────────────────────
// Runs like "7 + 8 = 15" or "x = −3" are isolated as LTR so the bidi algorithm doesn't reorder them.
const MATH_RUN = /(?:(?<![֐-׿])-|[−(√π?☐0-9a-zA-Z])[0-9a-zA-Z.,/()+\-−×÷=<>≤≥≠±²³√π:^·|?☐° ]*[0-9a-zA-Z)²³π?☐°]|[0-9a-zA-Z?]/g
// Cut a run at the first ")" that closes nothing (e.g. "5): 5/6" → "5"), and drop a trailing "(" opener.
function balancedLength(run) {
  let depth = 0
  for (let i = 0; i < run.length; i++) {
    if (run[i] === '(') depth++
    else if (run[i] === ')') { if (!depth) return i; depth-- }
  }
  if (!depth) return run.length
  const lastOpen = run.lastIndexOf('(')
  return lastOpen > 0 ? lastOpen : run.length
}
export function MathText({ children, as: Tag = 'span', className }) {
  const text = String(children ?? '')
  const out = []
  const re = new RegExp(MATH_RUN.source, 'g')
  let last = 0, k = 0, m
  while ((m = re.exec(text))) {
    const core = m[0].slice(0, balancedLength(m[0])).replace(/\s+$/, '')
    if (!core) { re.lastIndex = m.index + 1; continue }
    re.lastIndex = m.index + core.length
    if (m.index > last) out.push(text.slice(last, m.index))
    out.push(/[+\-−×÷=<>≤≥≠/^]|\d\s+\d|,\s*\d/.test(core) && /[\d?a-zA-Z]/.test(core) ? <bdi key={k++} dir="ltr" className="mth-ltr">{core}</bdi> : core)
    last = m.index + core.length
  }
  if (last < text.length) out.push(text.slice(last))
  return <Tag className={className}>{out}</Tag>
}

