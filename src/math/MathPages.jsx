// ── answer input ───────────────────────────────
function AnswerInput({ ex, value, onChange, onSubmit, disabled, idPrefix = 'ans', autoFocus, state }) {
  const ref = useRef(null)
  useEffect(() => { if (autoFocus && ref.current && !disabled) ref.current.focus({ preventScroll: true }) }, [autoFocus, disabled, ex])
  if (ex.type === 'choice') {
    return <div className="mth-choices" role="group" aria-label="בחירת תשובה">
      {ex.choices.map(c => {
        const picked = value === c
        const cls = state && (c === String(ex.answer) ? 'is-right' : picked ? 'is-wrong' : '')
        return <button key={c} type="button" className={`mth-choice ${picked ? 'is-picked' : ''} ${cls || ''}`} aria-pressed={picked} disabled={disabled} onClick={() => { onChange(c); onSubmit?.(c) }}><MathText>{c}</MathText></button>
      })}
    </div>
  }
  const kb = ex.type === 'number' ? 'decimal' : 'text'
  const extraKeys = ex.type === 'fraction' ? ['/', '−', ' '] : ex.type === 'numbers' ? [',', '−', '/'] : ex.type === 'number' ? [...(ex.grade >= 6 ? ['−'] : []), ...(ex.grade >= 5 ? ['.'] : [])] : []
  const hint = ex.type === 'fraction' ? 'למשל 3/4 או 1 1/2' : ex.type === 'numbers' ? 'מפרידים בפסיק, למשל 2, −3' : ''
  const press = k => { const v = (value || '') + k; onChange(v); ref.current?.focus() }
  return <div className="mth-input-row">
    <label className="sr-only" htmlFor={`${idPrefix}-in`}>התשובה שלך</label>
    <input id={`${idPrefix}-in`} ref={ref} className={`mth-input ${state || ''}`} dir="ltr" inputMode={kb} autoComplete="off" autoCorrect="off" spellCheck="false" enterKeyHint="done"
      value={value || ''} disabled={disabled} placeholder="?" onChange={e => onChange(e.target.value)}
      onKeyDown={e => { if (e.key === 'Enter') { e.preventDefault(); onSubmit?.(value) } }} />
    {ex.unit && <span className="mth-unit">{ex.unit}</span>}
    {!disabled && extraKeys.length > 0 && <span className="mth-keys">{extraKeys.map(k => <button key={k} type="button" onClick={() => press(k)} aria-label={k === ' ' ? 'רווח' : k === '−' ? 'מינוס' : k === '/' ? 'קו שבר' : k}>{k === ' ' ? '␣' : k}</button>)}</span>}
    {hint && <small className="mth-hint">{hint}</small>}
  </div>
}

// ── practice: one exercise at a time, endless ───────────────────────────────
function Practice({ topic, level }) {
  // The first exercise comes from a stable seed (prerendered HTML = hydrated HTML); later ones are random.
  const key = `${topic.grade}/${topic.slug}/${level}`
  const [cur, setCur] = useState(() => ({ key, ex: makeLevelExercise(topic, level, pageSeed(key)) }))
  const [value, setValue] = useState('')
  const [result, setResult] = useState(null) // null | 'right' | 'wrong'
  const [score, setScore] = useState({ right: 0, total: 0, streak: 0, best: 0 })
  const nextRef = useRef(null)
  // Level changed: a new exercise that only this level has (never one the easier level also shows).
  if (cur.key !== key) { setCur({ key, ex: makeLevelExercise(topic, level, newSeed()) }); setValue(''); setResult(null) }
  const ex = cur.ex
  useEffect(() => { if (result) nextRef.current?.focus({ preventScroll: true }) }, [result])
  const submit = v => {
    if (result || isBlank(v ?? value)) return
    const ok = checkAnswer(ex, v ?? value)
    setResult(ok ? 'right' : 'wrong')
    setScore(s => { const streak = ok ? s.streak + 1 : 0; return { right: s.right + (ok ? 1 : 0), total: s.total + 1, streak, best: Math.max(s.best, streak) } })
  }
  const next = () => {
    let n
    for (let i = 0; i < 5; i++) { n = makeExercise(topic, level, newSeed()); if (n.q !== ex.q || n.expr !== ex.expr || n.svg !== ex.svg) break }
    setCur({ key, ex: n }); setValue(''); setResult(null)
  }
  return <section className="ln-box mth-card" aria-labelledby="practice-h">
    <div className="mth-score" aria-live="polite">
      <h2 id="practice-h" className="text-xl font-black m-0">✏️ תרגול</h2>
      <span>✅ {score.right}/{score.total}</span>
      <span title="תשובות נכונות ברצף">🔥 רצף {score.streak}{score.best > 1 ? ` (שיא ${score.best})` : ''}</span>
    </div>
    <div className={`mth-ex ${result === 'right' ? 'flash-ok' : result === 'wrong' ? 'flash-no' : ''}`}>
      <Expr ex={ex} />
      <AnswerInput ex={ex} value={value} onChange={setValue} onSubmit={submit} disabled={!!result} state={result === 'right' ? 'is-right' : result === 'wrong' ? 'is-wrong' : ''} />
    </div>
    {!result && ex.type !== 'choice' && <div className="mth-actions"><button type="button" className="ln-btn go" onClick={() => submit()} disabled={isBlank(value)}>בדיקה ✓</button></div>}
    {result && <div className={`mth-feedback ${result}`} role="status">
      <p className="mth-verdict">{result === 'right' ? '✓ נכון, כל הכבוד!' : <>✗ לא בדיוק. התשובה הנכונה: <bdi dir="ltr" className="mth-ltr">{formatAnswer(ex)}</bdi>{ex.unit ? ` ${ex.unit}` : ''}</>}</p>
      <MathText as="p" className="mth-explain">{ex.explain}</MathText>
      <button ref={nextRef} type="button" className="ln-btn go" onClick={next}>תרגיל הבא ←</button>
    </div>}
  </section>
}

// ── quiz: n questions, answers checked at the end ───────────────────────────────
const mmss = s => `${Math.floor(s / 60)}:${String(s % 60).padStart(2, '0')}`

function Quiz({ items, timer, onRestart, onPrint, title }) {
  const [i, setI] = useState(0)
  const [answers, setAnswers] = useState(() => items.map(() => ''))
  const [done, setDone] = useState(false)
  const [secs, setSecs] = useState(0)
  const t0 = useRef(0)
  useEffect(() => { t0.current = Date.now() }, [])
  useEffect(() => {
    if (!timer || done) return
    const id = setInterval(() => setSecs(Math.floor((Date.now() - t0.current) / 1000)), 500)
    return () => clearInterval(id)
  }, [timer, done])
  const set = v => setAnswers(a => a.map((x, k) => (k === i ? v : x)))
  const answered = answers.filter(a => !isBlank(a)).length
  const results = done ? items.map((ex, k) => checkAnswer(ex, answers[k])) : []
  const right = results.filter(Boolean).length
  const finish = () => { setSecs(Math.floor((Date.now() - t0.current) / 1000)); setDone(true); window.scrollTo?.({ top: 0, behavior: 'smooth' }) }
  if (done) {
    const pct = Math.round((right / items.length) * 100)
    return <section className="ln-box mth-card" aria-labelledby="quiz-res">
      <h2 id="quiz-res" className="text-3xl font-black text-center">{pct >= 90 ? '🏆' : pct >= 70 ? '🌟' : pct >= 50 ? '👍' : '💪'} {right} מתוך {items.length} — ציון {pct}</h2>
      {timer && <p className="text-center font-bold">⏱️ זמן: {mmss(secs)}</p>}
      <p className="text-center">{pct >= 90 ? 'מצוין! שולטים בחומר.' : pct >= 70 ? 'יפה מאוד! כדאי לעבור על הטעויות למטה.' : 'כדאי לעבור על ההסברים למטה ולתרגל עוד קצת.'}</p>
      <div className="mth-actions"><button type="button" className="ln-btn go" onClick={onRestart}>🔁 מבחן חדש</button>{onPrint && <button type="button" className="ln-btn alt" onClick={onPrint}>🖨️ הדפסת המבחן</button>}</div>
      <h3 className="mt-6 mb-2 text-xl font-black">סקירת התשובות</h3>
      <ol className="mth-review">{items.map((ex, k) => <li key={k} className={results[k] ? 'ok' : 'no'}>
        {ex.topicTitle && <small className="mth-tag">{ex.topicEmoji} {ex.topicTitle}</small>}
        <Expr ex={ex} big={false} />
        <p className="m-0"><b>{results[k] ? '✓' : '✗'}</b> התשובה שלך: <bdi dir="ltr" className="mth-ltr">{answers[k] || '—'}</bdi>{!results[k] && <> · התשובה הנכונה: <bdi dir="ltr" className="mth-ltr">{formatAnswer(ex)}</bdi>{ex.unit ? ` ${ex.unit}` : ''}</>}</p>
        {!results[k] && <MathText as="p" className="mth-explain">{ex.explain}</MathText>}
      </li>)}</ol>
    </section>
  }
  const ex = items[i]
  return <section className="ln-box mth-card" aria-label={title}>
    <div className="mth-score"><b>שאלה {i + 1} מתוך {items.length}</b><span>נענו {answered}</span>{timer && <span>⏱️ {mmss(secs)}</span>}</div>
    <div className="ln-bar my-2"><i style={{ width: `${((i + 1) / items.length) * 100}%` }} /></div>
    <div className="mth-dots" role="group" aria-label="מעבר לשאלה">{items.map((_, k) => <button key={k} type="button" className={`${k === i ? 'is-on' : ''} ${!isBlank(answers[k]) ? 'is-done' : ''}`} onClick={() => setI(k)} aria-label={`שאלה ${k + 1}`} aria-current={k === i}>{k + 1}</button>)}</div>
    <div className="mth-ex">
      {ex.topicTitle && <small className="mth-tag">{ex.topicEmoji} {ex.topicTitle}</small>}
      <Expr ex={ex} />
      <AnswerInput key={i} idPrefix={`q${i}`} ex={ex} value={answers[i]} onChange={set} autoFocus onSubmit={() => { if (i < items.length - 1) setI(i + 1) }} />
    </div>
    <div className="mth-actions">
      <button type="button" className="ln-btn alt" disabled={i === 0} onClick={() => setI(i - 1)}>→ הקודמת</button>
      {i < items.length - 1 ? <button type="button" className="ln-btn" onClick={() => setI(i + 1)}>הבאה ←</button>
        : <button type="button" className="ln-btn go" onClick={finish}>סיום ובדיקה ✓</button>}
    </div>
    {i < items.length - 1 && answered === items.length && <p className="text-center mt-3"><button type="button" className="underline font-bold" onClick={finish}>ענית על הכול — לסיום ובדיקה</button></p>}
  </section>
}

