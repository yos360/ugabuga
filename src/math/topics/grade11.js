const norm360 = d => { let v = Math.round(d * 1e6) / 1e6 % 360; if (v < 0) v += 360; return Math.abs(v - 360) < 1e-6 ? 0 : v }
const uniq = xs => [...new Set(xs.map(v => Math.round(v * 1e6) / 1e6))]
function baseSolutions(fn, v) {
  if (fn === 'sin') { const a = Math.asin(v) / DEG; return uniq([norm360(a), norm360(180 - a)]) }
  if (fn === 'cos') { const a = Math.acos(v) / DEG; return uniq([norm360(a), norm360(-a)]) }
  const a = Math.atan(v) / DEG; return uniq([norm360(a), norm360(a + 180)])
}

