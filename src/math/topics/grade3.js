// Triangle with the given angles (degrees), scaled into a 220×170 box, angles dealt to random corners.
function triangleWithAngles(r, angles) {
  const [A, B, C] = r.shuffle(angles).map(d => (d * Math.PI) / 180)
  const b = Math.sin(B), c = Math.sin(C)
  let pts = [[0, 0], [c, 0], [b * Math.cos(A), -b * Math.sin(A)]]
  const xs = pts.map(p => p[0]), ys = pts.map(p => p[1])
  const w = Math.max(...xs) - Math.min(...xs), h = Math.max(...ys) - Math.min(...ys)
  const s = Math.min(190 / w, 140 / h)
  pts = pts.map(([x, y]) => [15 + (x - Math.min(...xs)) * s, 15 + (y - Math.min(...ys)) * s])
  return pts
}

