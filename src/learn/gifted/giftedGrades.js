// ── advanced number series (rule-based, like giftedGenerated.js): [rule, wrong[3]] ──
const AS = [
  [{ k: 'affine', a: 1, m: 3, c: 1 }, [363, 243, 365]],
  [{ k: 'grow', a: 1, d: 2, dd: 2 }, [41, 45, 39]],
  [{ k: 'inter', x: { a: 2, d: 4 }, y: { a: 30, d: -3 } }, [21, 12, 16]],
  [{ k: 'cycle', a: 5, ops: [['*', 2], ['-', 3]] }, [44, 25, 17]],
  [{ k: 'fib', a: 3, b: 4 }, [40, 49, 58]],
  [{ k: 'squares', from: 5 }, [98, 90, 121]],
  [{ k: 'cycle', a: 2, ops: [['*', 3], ['-', 1]] }, [43, 126, 45]],
  [{ k: 'grow', a: 100, d: -2, dd: -2 }, [60, 56, 64]],
  [{ k: 'affine', a: 2, m: 3, c: -2 }, [246, 164, 242]],
  [{ k: 'cycle', a: 1, ops: [['+', 1], ['*', 2]] }, [12, 21, 20]],
]
const LEN = { affine: 5, grow: 6, inter: 6, cycle: 6, fib: 6, squares: 5 }
export function seriesTerm(rule, i) {
  switch (rule.k) {
    case 'cycle': { let x = rule.a; for (let j = 0; j < i; j++) { const [o, n] = rule.ops[j % rule.ops.length]; x = o === '+' ? x + n : o === '-' ? x - n : o === '*' ? x * n : x / n } return x }
    case 'grow': { let x = rule.a; for (let j = 0; j < i; j++) x += rule.d + j * rule.dd; return x }
    case 'fib': { let a = rule.a, b = rule.b; for (let j = 0; j < i; j++) [a, b] = [b, a + b]; return a }
    case 'squares': return (rule.from + i) ** 2
    case 'affine': { let x = rule.a; for (let j = 0; j < i; j++) x = rule.m * x + rule.c; return x }
    case 'inter': { const s = i % 2 === 0 ? rule.x : rule.y; return s.a + s.d * Math.floor(i / 2) }
    default: throw new Error('unknown rule ' + rule.k)
  }
}

const id = (p, i) => `${p}${String(i + 1).padStart(2, '0')}`
export const ADV_VERBAL = AV.map(([a, b, c, ok, wrong, exp], i) => ({ id: id('av', i), level: 4, pair: [a, b], ask: c, ...place(id('av', i), ok, wrong), exp }))
export const ADV_LOGIC = AL.map(([q, ok, wrong, exp], i) => ({ id: id('al', i), level: 4, q, ...place(id('al', i), ok, wrong), exp }))
export const ADV_SERIES = AS.map(([rule, wrong], i) => {
  const n = LEN[rule.k], seq = Array.from({ length: n }, (_, j) => seriesTerm(rule, j))
  return { id: id('as', i), level: 4, rule, seq, ...place(id('as', i), seriesTerm(rule, n), wrong) }
})
export const ADVANCED = [
  ...ADV_VERBAL.map(item => ({ type: 'verbal', item })),
  ...ADV_SERIES.map(item => ({ type: 'series', item })),
  ...ADV_LOGIC.map(item => ({ type: 'logic', item })),
]

// Round-robin over the four types, so every printed set of 10 mixes them.
function interleave(lists) {
  const out = [], max = Math.max(...lists.map(l => l.length))
  for (let i = 0; i < max; i++) for (const l of lists) if (l[i]) out.push(l[i])
  return out
}
const byLevels = levels => interleave([
  ...TYPES.map(t => t.items.filter(it => levels.includes(it.level)).map(item => ({ type: t.key, item }))),
  ...(levels.includes(4) ? [ADV_VERBAL, ADV_SERIES, ADV_LOGIC].map((l, k) => l.map(item => ({ type: ['verbal', 'series', 'logic'][k], item }))) : []),
])

