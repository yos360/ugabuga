// The correct option is written first in the data; move it to a fixed, varied position.
export function placeQuiz(topicSlug, quiz) {
  return quiz.map((q, i) => {
    const id = `${topicSlug}-${i}`
    const pos = [...id].reduce((h, c) => (h * 31 + c.charCodeAt(0)) >>> 0, 7) % 4
    const options = q.options.slice(1); options.splice(pos, 0, q.options[0])
    return { ...q, options, answer: pos }
  })
}
