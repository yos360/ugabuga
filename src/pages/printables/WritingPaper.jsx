const SIBLINGS = Object.entries(KINDS).map(([k, v]) => ({ href: `/printables/${k}`, label: v.label }))

function PaperSheet({ kind, opt }) {
  const g = []
  const line = (x1, y1, x2, y2, stroke = '#9aa4b2', w = 0.25, dash) => g.push(<line key={g.length} x1={x1} y1={y1} x2={x2} y2={y2} stroke={stroke} strokeWidth={w} strokeDasharray={dash} />)
  if (kind === 'lined-paper') {
    const step = +opt
    for (let y = TOP + step; y <= H - 2; y += step) line(0, y, W, y)
    line(W - 14, 0, W - 14, H, '#e88', 0.35)
    g.push(<T key="n" x={W - 16} y={7} size={4} anchor="end" fill="#aaa">תאריך: __________</T>)
  } else if (kind === 'grid-paper') {
    const step = +opt, nx = Math.floor(W / step), ny = Math.floor((H - TOP) / step), x0 = (W - nx * step) / 2
    for (let i = 0; i <= nx; i++) line(x0 + i * step, TOP, x0 + i * step, TOP + ny * step)
    for (let j = 0; j <= ny; j++) line(x0, TOP + j * step, x0 + nx * step, TOP + j * step)
  } else if (kind === 'graph-paper') {
    const c = opt === 'blue' ? '#3aa7a0' : '#8f98a6', nx = Math.floor(W / 10) * 10, ny = Math.floor((H - TOP) / 10) * 10, x0 = (W - nx) / 2
    for (let i = 0; i <= nx; i++) line(x0 + i, TOP, x0 + i, TOP + ny, c, i % 10 === 0 ? 0.35 : i % 5 === 0 ? 0.2 : 0.07)
    for (let j = 0; j <= ny; j++) line(x0, TOP + j, x0 + nx, TOP + j, c, j % 10 === 0 ? 0.35 : j % 5 === 0 ? 0.2 : 0.07)
  } else if (kind === 'dot-paper') {
    const step = +opt, nx = Math.floor(W / step), ny = Math.floor((H - TOP) / step), x0 = (W - nx * step) / 2
    for (let i = 0; i <= nx; i++) for (let j = 0; j <= ny; j++) g.push(<circle key={g.length} cx={x0 + i * step} cy={TOP + j * step} r={step > 6 ? 0.7 : 0.4} fill="#555" />)
  } else if (kind === 'english-lines') {
    const big = opt === 'big', x = big ? 7 : 5, gap = big ? 9 : 6
    for (let y = TOP + 6; y + 3 * x <= H; y += 3 * x + gap) {
      line(0, y, W, y, '#9aa4b2', 0.3); line(0, y + x, W, y + x, '#9aa4b2', 0.25, '1.5 1.2'); line(0, y + 2 * x, W, y + 2 * x, '#555', 0.4)
      line(0, y + 3 * x, W, y + 3 * x, '#ddd', 0.2, '0.6 1')
    }
  } else if (kind === 'music-paper') {
    const n = +opt, sp = opt === '10' ? 1.9 : 1.75, block = (H - TOP) / n
    for (let s = 0; s < n; s++) {
      const y0 = TOP + s * block + (block - 4 * sp * 1.0) / 2
      for (let k = 0; k < 5; k++) line(3, y0 + k * sp, W - 3, y0 + k * sp, '#333', 0.25)
      line(3, y0, 3, y0 + 4 * sp, '#333', 0.3); line(W - 3, y0, W - 3, y0 + 4 * sp, '#333', 0.3)
    }
  }
  return <Sheet w={W} h={H} label={KINDS[kind].h1}>{g}</Sheet>
}

export default function WritingPaper({ kind }) {
  const k = KINDS[kind]
  const [opt, setOpt] = useState(k.def)
  return <PrintableShell path={`/printables/${kind}`} emoji={k.emoji} h1={k.h1} sub={k.sub} seoTitle={k.seoTitle} description={k.description}
    crumbs={[{ label: 'לכיתה ולגן', href: '/printables?topic=school' }]} siblings={SIBLINGS}
    controls={<Choice label="סוג" value={opt} onChange={setOpt} options={k.options} />}
    pages={[{ key: kind + opt, svg: <PaperSheet kind={kind} opt={opt} /> }]}
    extra={<p className="text-sm text-[var(--muted-foreground)]">טיפ: בחלון ההדפסה בחרו "גודל בפועל" (100%) כדי שהמרווחים יצאו מדויקים.</p>}
    paragraphs={k.paragraphs} faq={k.faq}
    related={[{ label: 'אותיות עברית למעבר בעיפרון', href: '/printables/hebrew-letters' }, { label: 'דפי עבודה בחשבון', href: '/printables/math-worksheets' }, { label: 'מערכת שעות', href: '/printables/class-schedule' }]} />
}
